use std::collections::BTreeMap;

use rustegon_common::Error;
use rustegon_doc::{Document, Value, compare::compare};

use self::error::unsupported;
pub use self::error::{UNSUPPORTED_DETAIL, is_unsupported};
use crate::ast::{QualifiedName, Statement};

/// Statement parameters: `$name` → `"name"`, `$1` → `"1"`.
pub type Params = BTreeMap<String, Value>;

/// Result of a statement.
#[derive(Debug, Clone, PartialEq, Default)]
pub struct Output {
    /// Result rows: documents (as [`Value::Object`]) or `SELECT VALUE` values for reads;
    /// `RETURNING` images for writes (empty without `RETURNING`).
    pub rows: Vec<Value>,
    /// Documents written (`None` for reads).
    pub affected: Option<u64>,
}

/// The in-memory store and statement context of the reference interpreter.
#[derive(Debug, Clone)]
pub struct Reference {
    /// Collections, each sorted by `_id` in the §2.1 total order.
    store: BTreeMap<String, Vec<Document>>,
    /// Value of `now()` and `CURRENT DATE` (ms since the epoch): the statement's transaction
    /// timestamp in the real engine, a fixed instant here so results are reproducible.
    now_ms: i64,
    /// Counter for `_id`s generated by inserts without one (deterministic, see [`write`]).
    next_oid: u64,
}

/// Default `now()` of a new interpreter: 2026-01-01T00:00:00Z.
pub const DEFAULT_NOW_MS: i64 = 1_767_225_600_000;

impl Default for Reference {
    fn default() -> Self {
        Self::new()
    }
}

impl Reference {
    /// An empty store with `now()` = [`DEFAULT_NOW_MS`].
    #[must_use]
    pub fn new() -> Self {
        Self {
            store: BTreeMap::new(),
            now_ms: DEFAULT_NOW_MS,
            next_oid: 0,
        }
    }

    /// Sets the instant returned by `now()` / stored by `CURRENT DATE`.
    pub fn set_now_ms(&mut self, now_ms: i64) {
        self.now_ms = now_ms;
    }

    /// Removes every collection.
    pub fn clear(&mut self) {
        self.store.clear();
    }

    /// Appends documents to `collection` (created when absent), keeping it sorted by `_id`.
    /// Loading bypasses statement validation: it is the test fixture path.
    pub fn load(&mut self, collection: &str, docs: impl IntoIterator<Item = Document>) {
        let coll = self.store.entry(collection.to_owned()).or_default();
        coll.extend(docs);
        sort_by_id(coll);
    }

    /// The documents of `collection` in `_id` order (empty when absent).
    #[must_use]
    pub fn documents(&self, collection: &str) -> &[Document] {
        self.store.get(collection).map_or(&[], Vec::as_slice)
    }

    /// Executes one statement.
    ///
    /// # Errors
    /// The error the specification assigns (codes of query-language.md §14, data-model §2.3),
    /// or an error carrying [`UNSUPPORTED_DETAIL`] for features outside the reference scope.
    pub fn execute(&mut self, stmt: &Statement, params: &Params) -> Result<Output, Error> {
        let ctx = eval::Ctx {
            params,
            now_ms: self.now_ms,
        };
        match stmt {
            Statement::Query(q) => {
                let rows = query::run(self, q, &ctx)?;
                Ok(Output {
                    rows,
                    affected: None,
                })
            }
            Statement::Insert(s) => write::insert(self, s, &ctx),
            Statement::Update(s) => write::update(self, s, &ctx),
            Statement::Upsert(s) => write::upsert(self, s, &ctx),
            Statement::Delete(s) => write::delete(self, s, &ctx),
            _ => Err(unsupported("statement kind outside the M3 reference scope")),
        }
    }

    pub(crate) fn collection(&self, name: &QualifiedName) -> &[Document] {
        self.documents(&collection_key(name))
    }

    pub(crate) fn replace_collection(&mut self, name: &QualifiedName, mut docs: Vec<Document>) {
        sort_by_id(&mut docs);
        self.store.insert(collection_key(name), docs);
    }

    pub(crate) fn fresh_object_id(&mut self) -> Value {
        // Deterministic ids (prefix 0xFF… sorts after realistic ids): reproducible runs. The
        // harness never compares documents with generated ids across engines.
        self.next_oid += 1;
        let mut bytes = [0xFF_u8; 12];
        bytes[4..].copy_from_slice(&self.next_oid.to_be_bytes());
        Value::ObjectId(rustegon_doc::ObjectId(bytes))
    }
}

/// Store key of a collection: `name`, or `database.name` when the database is given.
#[must_use]
pub fn collection_key(name: &QualifiedName) -> String {
    match &name.database {
        Some(db) => format!("{db}.{}", name.name),
        None => name.name.clone(),
    }
}

/// Stable sort by `_id` (missing first, as §2.1 orders it).
fn sort_by_id(docs: &mut [Document]) {
    docs.sort_by(|a, b| compare(a.get("_id"), b.get("_id")));
}
