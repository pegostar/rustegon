//! Naive reference interpreter of RGQL (query-engine.md §11; FR-QL; TC-QL-009/010).
//!
//! Purpose: the oracle of differential testing. It evaluates a parsed [`Statement`] directly
//! against an in-memory store (`collection → documents`), with no binder, planner, index or
//! optimisation, so that its behaviour can be read off the specification. It shares no
//! evaluation code with the real executor; it reuses only the document model
//! (`rustegon_doc::compare` for the §2.1 total order and `rustegon_doc::update::apply_updates`
//! for the data-model §2.3 update operators, which have their own reference tests TC-DOC-009…012).
//! Simplicity beats speed everywhere: rows are cloned, every predicate is evaluated in full.
//!
//! # Scope (M3)
//! `FROM <collection> [AS a] [WHERE] [SELECT * | items | VALUE] [ORDER BY] [LIMIT/OFFSET]`,
//! `INSERT` (`VALUE`, `VALUES`, query source, `ON CONFLICT`), `UPDATE` (every operator,
//! `REPLACE WITH`, array filters), `UPSERT`, `DELETE`, `RETURNING`. Lookups, grouping, pipelines,
//! sub-query sources, `INCLUDE`, aggregates, full-text, geo, vector and date functions (M7)
//! fail with an error carrying the detail [`UNSUPPORTED_DETAIL`]; DDL, transactions and admin
//! statements too.
//!
//! # Semantics
//! Expression semantics are documented in [`eval`], [`predicate`], [`arith`] and [`func`];
//! query-level rules in [`query`] and write rules in [`write`](mod@write). Choices the specification leaves
//! open are marked *Provisional* there and in query-language.md §4.3.
//!
//! **Row order.** The store keeps each collection sorted by `_id` (§2.1 total order); a scan
//! returns rows in that order. `ORDER BY` sorts stably by its keys and breaks ties by `_id`
//! ascending, so every reference result is deterministic. Results of a query without `ORDER BY`
//! are only meaningful as a multiset (the differential harness compares them that way).

