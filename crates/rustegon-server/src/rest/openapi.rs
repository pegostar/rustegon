/// Tag of operations that skip the common request headers (see the module docs).
const HEALTH_TAG: &str = "health";

/// Request headers of protocol.md §2 shared by every non-probe operation.
const REQUEST_HEADERS: [(&str, &str); 5] = [
    (
        REQUEST_ID,
        "Client-generated UUIDv7 that makes retries idempotent (protocol.md §5.1); generated by \
         the server when absent.",
    ),
    (
        TRACEPARENT,
        "W3C Trace Context; an invalid value is ignored and a new trace is started.",
    ),
    (
        TIMEOUT_HEADER,
        "Request timeout in milliseconds (1 to 8 decimal digits); becomes the request deadline \
         (protocol.md §5.2). An expired deadline fails with RGN-5006.",
    ),
    (
        TXN_ID,
        "Interactive transaction the request runs in (at most 256 visible ASCII bytes).",
    ),
    (
        CAUSALITY_TOKEN,
        "Causality token from an earlier response, for session consistency (at most 4 KiB of \
         visible ASCII).",
    ),
];

/// The generated document.
#[must_use]
pub fn openapi() -> openapi::OpenApi {
    let (_, mut doc) = super::api().split_for_parts();
    doc.info.version = format!("{PROTOCOL_MAJOR}.{PROTOCOL_MINOR}");
    add_components(&mut doc);
    for item in doc.paths.paths.values_mut() {
        for op in [
            &mut item.get,
            &mut item.put,
            &mut item.post,
            &mut item.delete,
            &mut item.patch,
            &mut item.head,
            &mut item.options,
        ]
        .into_iter()
        .flatten()
        {
            decorate(op);
        }
    }
    doc
}

/// The generated document as YAML: the content of `api/openapi/rustegon-v1.yaml`.
///
/// # Errors
/// Only if serialization fails, which would be a bug in the document types.
pub fn openapi_yaml() -> Result<String, serde_json::Error> {
    let json = serde_json::to_value(openapi())?;
    let mut out = String::new();
    let mut emitter = YamlEmitter::new(&mut out);
    // Every value is a plain scalar, sequence or mapping; emitting into a String cannot fail
    // except on formatter errors, which String never returns.
    let _ = emitter.dump(&to_yaml(&json));
    out.push('\n');
    Ok(out)
}

fn to_yaml(value: &serde_json::Value) -> Yaml {
    match value {
        serde_json::Value::Null => Yaml::Null,
        serde_json::Value::Bool(b) => Yaml::Boolean(*b),
        serde_json::Value::Number(n) => n
            .as_i64()
            .map_or_else(|| Yaml::Real(n.to_string()), Yaml::Integer),
        serde_json::Value::String(s) => Yaml::String(s.clone()),
        serde_json::Value::Array(items) => Yaml::Array(items.iter().map(to_yaml).collect()),
        serde_json::Value::Object(map) => {
            let mut hash = Hash::new();
            for (k, v) in map {
                hash.insert(Yaml::String(k.clone()), to_yaml(v));
            }
            Yaml::Hash(hash)
        }
    }
}

fn string_schema() -> ObjectBuilder {
    ObjectBuilder::new().schema_type(Type::String)
}

fn add_components(doc: &mut openapi::OpenApi) {
    let components = doc.components.get_or_insert_with(Default::default);
    for (name, description) in REQUEST_HEADERS {
        let schema = if name == TIMEOUT_HEADER {
            ObjectBuilder::new()
                .schema_type(Type::Integer)
                .minimum(Some(0))
                .maximum(Some(99_999_999))
        } else {
            string_schema()
        };
        components.parameters.insert(
            name.to_owned(),
            RefOr::T(
                ParameterBuilder::new()
                    .name(name)
                    .parameter_in(ParameterIn::Header)
                    .required(Required::False)
                    .description(Some(description))
                    .schema(Some(schema))
                    .build(),
            ),
        );
    }
    for (name, description, schema) in [
        (
            NODE_ID,
            "Id of the node that served the request.",
            ObjectBuilder::new()
                .schema_type(Type::Integer)
                .minimum(Some(0)),
        ),
        (
            SERVER_TIME,
            "Server wall clock when the response was produced (Unix milliseconds).",
            ObjectBuilder::new()
                .schema_type(Type::Integer)
                .minimum(Some(0)),
        ),
        (
            CAUSALITY_TOKEN,
            "Newest causality token of the session; send it back in later requests.",
            string_schema(),
        ),
    ] {
        components.headers.insert(
            name.to_owned(),
            RefOr::T(
                HeaderBuilder::new()
                    .description(Some(description))
                    .schema(Some(schema))
                    .build(),
            ),
        );
    }
    components.responses.insert(
        "Error".to_owned(),
        RefOr::T(
            ResponseBuilder::new()
                .description(
                    "Error (protocol.md §7): the HTTP status follows the error catalog and the \
                     body identifies the Rustegon code.",
                )
                .content(
                    "application/json",
                    ContentBuilder::new()
                        .schema(Some(Ref::from_schema_name(ErrorBody::name())))
                        .build(),
                )
                .header_ref(NODE_ID, header_ref(NODE_ID))
                .header_ref(SERVER_TIME, header_ref(SERVER_TIME))
                .build(),
        ),
    );
    add_security_schemes(components);
}

/// The three ways to authenticate (security.md §2.1). Operations that require a caller list
/// them in their `security(...)` attribute.
fn add_security_schemes(components: &mut openapi::Components) {
    components.security_schemes.insert(
        "bearer".to_owned(),
        RefOr::T(SecurityScheme::Http(
            HttpBuilder::new()
                .scheme(HttpAuthScheme::Bearer)
                .description(Some(
                    "Session token from the login endpoints: `Authorization: Bearer <token>`.",
                ))
                .build(),
        )),
    );
    components.security_schemes.insert(
        "apiKey".to_owned(),
        RefOr::T(SecurityScheme::ApiKey(ApiKey::Header(
            ApiKeyValue::with_description(
                "Authorization",
                "API key for automation: `Authorization: ApiKey rgn_<key_id>_<secret>`.",
            ),
        ))),
    );
    components.security_schemes.insert(
        "sessionCookie".to_owned(),
        RefOr::T(SecurityScheme::ApiKey(ApiKey::Cookie(
            ApiKeyValue::with_description(
                SESSION_COOKIE.to_owned(),
                format!(
                    "GUI session cookie. State-changing requests authenticated by it must send \
                     the `{CSRF_HEADER}` header with the CSRF token of the session."
                ),
            ),
        ))),
    );
}

/// Reference to a shared response header.
fn header_ref(name: &str) -> Ref {
    Ref::new(format!("#/components/headers/{name}"))
}

fn decorate(op: &mut Operation) {
    let probe = op
        .tags
        .as_ref()
        .is_some_and(|tags| tags.iter().any(|t| t == HEALTH_TAG));
    if !probe {
        let params = op.parameters.get_or_insert_with(Vec::new);
        for (name, _) in REQUEST_HEADERS {
            params.push(RefOr::Ref(Ref::new(format!(
                "#/components/parameters/{name}"
            ))));
        }
    }
    for (status, response) in &mut op.responses.responses {
        if let RefOr::T(response) = response {
            for name in [NODE_ID, SERVER_TIME] {
                response
                    .headers
                    .insert(name.to_owned(), RefOr::Ref(header_ref(name)));
            }
            if !probe && status.starts_with('2') {
                response.headers.insert(
                    CAUSALITY_TOKEN.to_owned(),
                    RefOr::Ref(header_ref(CAUSALITY_TOKEN)),
                );
            }
        }
    }
    op.responses.responses.insert(
        "default".to_owned(),
        RefOr::Ref(Ref::new("#/components/responses/Error")),
    );
}
