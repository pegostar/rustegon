//! The `OpenAPI` 3.1 document of `/api/v1` (FR-API-002; PD-052), generated from the handlers'
//! `#[utoipa::path]` annotations and checked in as `api/openapi/rustegon-v1.yaml`.
//!
//! Handlers describe only what is specific to them (path, tag, operation id, success body).
//! What every operation shares is added here so it cannot be forgotten: the request headers of
//! protocol.md §2 (as `components.parameters`), the node response headers, the
//! `rgn-causality-token` response header and the `default` error response with
//! [`ErrorBody`]. Operations tagged `health` are probes that read no header and get only the
//! node headers.

use utoipa::{
    OpenApi, ToSchema,
    openapi::{
        self, Ref, RefOr, Required,
        content::ContentBuilder,
        header::HeaderBuilder,
        path::{Operation, ParameterBuilder, ParameterIn},
        response::ResponseBuilder,
        schema::{ObjectBuilder, Type},
        security::{ApiKey, ApiKeyValue, HttpAuthScheme, HttpBuilder, SecurityScheme},
    },
};
use yaml_rust2::{Yaml, YamlEmitter, yaml::Hash};

use super::{
    ErrorBody, ErrorInfo,
    auth::{CSRF_HEADER, SESSION_COOKIE},
    context::{
        CAUSALITY_TOKEN, NODE_ID, REQUEST_ID, SERVER_TIME, TIMEOUT_HEADER, TRACEPARENT, TXN_ID,
    },
};
use crate::services::{PROTOCOL_MAJOR, PROTOCOL_MINOR};

