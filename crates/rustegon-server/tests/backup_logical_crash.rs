//! Crash during a logical dump or restore (M13a lane BH1; FR-BKP-007, AC-BKP-006, TC-BKP-013
//! crash variants, PD-091), on the simulated file system: the process dies after `n` mutating
//! file-system operations and the machine loses power in one of the crash modes (all in turn).
//! - Dump: writes acknowledged while the dump ran survive; the interrupted stream (no
//!   `dump.json`) is refused by a restore, which leaves the target empty.
//! - Restore (`import_documents` batches into the live store): data that was in the target
//!   before is never touched; a collection of the restore is absent or holds a subset of the
//!   dump (committed batches survive a crash: PD-091, the "drop on failure" cleanup cannot run
//!   in a dead process); a rerun without `--drop` is refused cleanly (`RGN-1031`) when such a
//!   leftover exists and changes nothing; the rerun with `--drop` restores exactly the dump.

#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::too_many_lines
)]

use std::{
    collections::{BTreeMap, VecDeque},
    path::Path,
    sync::Arc,
    time::Duration,
};

use rustegon_backup::HlcTimestamp;
use rustegon_catalog::{DatabaseOptions, IndexField, IndexSpec};
use rustegon_common::{Error, ErrorCode};
use rustegon_doc::{
    Document, Value,
    json::{JsonMode, to_json},
};
use rustegon_engine::{
    EmbeddedDb,
    embedded::{FenceOptions, ScanOptions},
};
use rustegon_server::services::{
    backup::{DumpChunk, DumpScope, DumpSink, DumpSource, LogicalRestoreOptions},
    backup_logical::{CancelCheck, DumpOptions, dump_with, logical_restore},
};
use rustegon_sim::{
    CrashMode, SimFileSystem,
    workload::{clock::SimClock, rng::SimRng},
};
use rustegon_sim_api::FileSystem;

const T0: Duration = Duration::from_secs(1_700_000_000);
const TARGET: &str = "/target";
/// The dumped collections.
const COLLECTIONS: [(&str, &str); 3] = [("shop", "orders"), ("shop", "users"), ("crm", "leads")];

/// Documents (canonical JSON without `_rev`) and index names of one collection.
type Contents = (Vec<String>, Vec<String>);

struct Never;

impl CancelCheck for Never {
    fn check(&self) -> Result<(), Error> {
        Ok(())
    }
}

/// One simulated machine.
struct World {
    fs: Arc<SimFileSystem>,
    clock: Arc<SimClock>,
}

impl World {
    fn new() -> Self {
        Self {
            fs: Arc::new(SimFileSystem::new()),
            clock: Arc::new(SimClock::new(
                T0,
                Duration::from_micros(10),
                Duration::from_micros(10),
            )),
        }
    }

    fn open(&self, root: &str) -> Arc<EmbeddedDb> {
        Arc::new(
            EmbeddedDb::open(
                Arc::clone(&self.fs) as Arc<dyn FileSystem>,
                Path::new(root),
                Arc::clone(&self.clock) as Arc<dyn rustegon_sim_api::Clock>,
                Arc::new(SimRng::new(3)),
            )
            .unwrap_or_else(|e| panic!("open {root}: {e}")),
        )
    }

    fn crash(&self, n: u64) -> CrashMode {
        let mode = CrashMode::ALL[usize::try_from(n).unwrap() % CrashMode::ALL.len()];
        self.fs.crash(n, mode);
        self.clock.advance(Duration::from_secs(5));
        mode
    }
}

fn doc(id: i64, coll: &str) -> Document {
    Document::try_from_fields(vec![
        ("_id".to_owned(), Value::Int64(id)),
        ("n".to_owned(), Value::Int64(id % 7)),
        (
            "text".to_owned(),
            Value::String(format!("{coll}-{id}-{}", "x".repeat(40))),
        ),
    ])
    .unwrap()
}

fn populate(db: &EmbeddedDb) {
    for d in ["shop", "crm"] {
        db.create_database(d, &DatabaseOptions::default()).unwrap();
    }
    for (i, (d, c)) in COLLECTIONS.iter().enumerate() {
        for id in 0..(60 + 20 * i64::try_from(i).unwrap()) {
            db.insert(d, c, &doc(id, c)).unwrap();
        }
    }
    db.create_index(
        "shop",
        "orders",
        &IndexSpec::new("by_n", vec![IndexField::asc("n")]),
    )
    .unwrap();
}

/// Documents of `d.c` without `_rev` (regenerated by a restore), plus index names; `None`
/// when the collection does not exist.
fn contents(db: &Arc<EmbeddedDb>, d: &str, c: &str) -> Option<Contents> {
    match db.collection(d, c) {
        Ok(Some(_)) => {}
        Ok(None) => return None,
        Err(e) if e.code() == ErrorCode::NotFound => return None,
        Err(e) => panic!("{d}.{c}: {e}"),
    }
    let snapshot = Arc::new(db.pin_snapshot(&FenceOptions::default()).unwrap());
    let docs = db
        .scan_at(&snapshot, d, c, ScanOptions::default())
        .unwrap()
        .flat_map(Result::unwrap)
        .map(|mut doc| {
            doc.remove("_rev");
            to_json(&doc, JsonMode::Canonical)
        })
        .collect();
    let mut indexes: Vec<String> = db
        .list_indexes(d, c)
        .unwrap()
        .into_iter()
        .map(|i| i.name)
        .collect();
    indexes.sort();
    Some((docs, indexes))
}

#[derive(Default)]
struct MemSink {
    chunks: Vec<DumpChunk>,
    /// Runs before each chunk is delivered; `false` = the process died, nothing more is sent.
    hook: Option<Box<dyn FnMut() -> bool + Send>>,
}

impl DumpSink for MemSink {
    fn started(&mut self, _timestamp: HlcTimestamp) -> Result<(), Error> {
        Ok(())
    }

    fn chunk(&mut self, chunk: DumpChunk) -> Result<(), Error> {
        if let Some(hook) = &mut self.hook
            && !hook()
        {
            return Err(Error::new(
                ErrorCode::Unavailable,
                "the server process died",
            ));
        }
        self.chunks.push(chunk);
        Ok(())
    }
}

struct MemSource(VecDeque<DumpChunk>);

impl DumpSource for MemSource {
    fn next_chunk(&mut self) -> Result<Option<DumpChunk>, Error> {
        Ok(self.0.pop_front())
    }
}

fn small_chunks() -> DumpOptions {
    DumpOptions {
        chunk_bytes: 2048,
        ..DumpOptions::default()
    }
}

/// The dump of a populated source store, as chunks.
fn source_dump() -> (Vec<DumpChunk>, BTreeMap<String, Contents>) {
    let world = World::new();
    let db = world.open("/source");
    populate(&db);
    let mut sink = MemSink::default();
    dump_with(
        &db,
        &DumpScope::default(),
        &mut sink,
        &Never,
        &small_chunks(),
    )
    .unwrap();
    let want = COLLECTIONS
        .iter()
        .map(|(d, c)| (format!("{d}.{c}"), contents(&db, d, c).unwrap()))
        .collect();
    (sink.chunks, want)
}

fn restore(db: &Arc<EmbeddedDb>, chunks: &[DumpChunk], drop_existing: bool) -> Result<(), Error> {
    let mut source = MemSource(chunks.iter().cloned().collect());
    logical_restore(
        db,
        &LogicalRestoreOptions {
            drop_existing,
            scope: DumpScope::default(),
        },
        &mut source,
        &Never,
    )
    .map(|_| ())
}

/// Data of the target that is not part of the dump: never touched by the restore.
fn target_with_own_data(world: &World) -> Arc<EmbeddedDb> {
    let db = world.open(TARGET);
    db.create_database("keep", &DatabaseOptions::default())
        .unwrap();
    for id in 0..30 {
        db.insert("keep", "mine", &doc(id, "mine")).unwrap();
    }
    db
}

/// TC-BKP-013 crash variant (FR-BKP-007, PD-091): a crash at every operation of a logical
/// restore never touches the target's own data, leaves each restored collection absent or a
/// subset of the dump, and the rerun is refused cleanly without `--drop` (when a leftover
/// exists) and exact with `--drop`.
#[test]
fn tc_bkp_013_crash_during_logical_restore_keeps_existing_data_and_rerun_with_drop_is_exact() {
    let (chunks, want) = source_dump();
    let total = {
        let world = World::new();
        let db = target_with_own_data(&world);
        let before = world.fs.op_count();
        restore(&db, &chunks, false).unwrap();
        let ops = world.fs.op_count() - before;
        for (d, c) in COLLECTIONS {
            assert_eq!(
                contents(&db, d, c).as_ref(),
                Some(&want[&format!("{d}.{c}")])
            );
        }
        ops
    };
    assert!(total > 20, "restore ops: {total}");
    let stride = total.div_ceil(150).max(1);
    let mut partial_seen = false;
    for n in (0..=total).filter(|n| n % stride == 0 || total - n < 4) {
        let world = World::new();
        let db = target_with_own_data(&world);
        let own = contents(&db, "keep", "mine").unwrap();
        world.fs.halt_after_ops(n);
        let result = restore(&db, &chunks, false);
        let mode = world.crash(n);
        drop(db);
        let ctx = format!("op {n}/{total} {mode:?}");

        let db = world.open(TARGET);
        assert_eq!(
            contents(&db, "keep", "mine").as_ref(),
            Some(&own),
            "{ctx}: own data"
        );
        let mut leftover = false;
        for (d, c) in COLLECTIONS {
            let Some((docs, _)) = contents(&db, d, c) else {
                continue;
            };
            leftover = true;
            let (all, _) = &want[&format!("{d}.{c}")];
            for got in &docs {
                assert!(
                    all.contains(got),
                    "{ctx}: {d}.{c} holds {got} not in the dump"
                );
            }
            if result.is_ok() {
                assert_eq!(docs.len(), all.len(), "{ctx}: {d}.{c} lost documents");
            } else if docs.len() < all.len() {
                partial_seen = true;
            }
        }
        if result.is_ok() {
            assert!(leftover, "{ctx}: a completed restore was lost");
        } else {
            let before = (contents(&db, "keep", "mine"), names(&db));
            match restore(&db, &chunks, false) {
                Ok(()) => assert!(!leftover, "{ctx}: rerun without --drop over a leftover"),
                Err(e) => {
                    assert_eq!(e.code(), ErrorCode::AlreadyExists, "{ctx}: {e}");
                    assert!(leftover, "{ctx}");
                    assert_eq!((contents(&db, "keep", "mine"), names(&db)), before, "{ctx}");
                    restore(&db, &chunks, true)
                        .unwrap_or_else(|e| panic!("{ctx}: rerun with --drop: {e}"));
                }
            }
        }
        for (d, c) in COLLECTIONS {
            assert_eq!(
                contents(&db, d, c).as_ref(),
                Some(&want[&format!("{d}.{c}")]),
                "{ctx}: {d}.{c} after the rerun"
            );
        }
        assert_eq!(contents(&db, "keep", "mine").as_ref(), Some(&own), "{ctx}");
    }
    assert!(
        partial_seen,
        "no crash point left a partial collection behind"
    );
}

fn names(db: &Arc<EmbeddedDb>) -> Vec<String> {
    let mut out = Vec::new();
    for d in db.list_databases().unwrap() {
        for c in db.list_collections(&d.name).unwrap() {
            out.push(format!("{}.{}", d.name, c.name));
        }
        out.push(d.name);
    }
    out
}

/// TC-BKP-013 crash variant (FR-BKP-007): writes acknowledged while a dump streams survive a
/// crash at any point of it, and the interrupted stream (no `dump.json`) is refused by a
/// restore, which leaves the target empty.
#[test]
fn tc_bkp_013_crash_during_dump_keeps_acknowledged_writes_and_the_partial_dump_is_refused() {
    // One write per streamed chunk races the dump.
    let run = |world: &World, halt: Option<u64>| {
        let db = world.open("/source");
        populate(&db);
        let before = world.fs.op_count();
        if let Some(n) = halt {
            world.fs.halt_after_ops(n);
        }
        let acked = Arc::new(std::sync::Mutex::new(Vec::new()));
        let mut sink = MemSink::default();
        let (writer, log, fs) = (Arc::clone(&db), Arc::clone(&acked), Arc::clone(&world.fs));
        let mut next = 1000;
        sink.hook = Some(Box::new(move || {
            next += 1;
            if writer
                .insert("shop", "orders", &doc(next, "orders"))
                .is_ok()
            {
                log.lock().unwrap().push(next);
            }
            // A halted file system is a dead process: the stream stops at this point.
            !fs.is_halted()
        }));
        let result = dump_with(
            &db,
            &DumpScope::default(),
            &mut sink,
            &Never,
            &small_chunks(),
        );
        let ops = world.fs.op_count() - before;
        let acked = acked.lock().unwrap().clone();
        (db, result.is_ok(), sink.chunks, acked, ops)
    };
    let total = {
        let world = World::new();
        let (_, ok, _, acked, ops) = run(&world, None);
        assert!(ok);
        assert!(acked.len() > 5, "writes racing the dump: {}", acked.len());
        ops
    };
    assert!(total > 5, "dump-time ops: {total}");
    let mut refused = 0;
    for n in 0..total {
        let world = World::new();
        let (db, ok, chunks, acked, _) = run(&world, Some(n));
        let mode = world.crash(n);
        drop(db);
        let ctx = format!("op {n}/{total} {mode:?}");
        let db = world.open("/source");
        for id in &acked {
            assert!(
                db.get("shop", "orders", &Value::Int64(*id))
                    .unwrap()
                    .is_some(),
                "{ctx}: acknowledged write {id} lost"
            );
        }
        let Some(last) = chunks.last() else {
            continue;
        };
        if ok {
            continue;
        }
        // The stream ended early: whatever arrived must not restore anything.
        refused += 1;
        assert!(
            !(last.path == "dump.json" && last.end_of_file),
            "{ctx}: a complete stream"
        );
        let target = world.open(&format!("/t{n}"));
        let err = restore(&target, &chunks, false).unwrap_err();
        assert_eq!(err.code(), ErrorCode::InvalidArgument, "{ctx}: {err}");
        assert!(names(&target).is_empty(), "{ctx}: {:?}", names(&target));
    }
    assert!(refused > 0, "no crash point interrupted the dump stream");
}
