//! Field paths (data-model.md §2.2) and lazy path lookup over `RDoc` bytes (§4).
//!
//! Lookup semantics (both on decoded values and on bytes; TC-DOC-005 checks they agree):
//! a segment applied to an object selects the field of that name; an unquoted segment that is a
//! canonical decimal number (`0`, `17`, not `01`) applied to an array selects that element;
//! anything else yields `missing` (`None`). Fan-out over array elements (`a.b` where `a` is an
//! array of objects) is query-layer semantics (M3) and not done here.

use crate::{
    error::{DocError, DocResult},
    limits::MAX_FIELD_NAME_LEN,
    rdoc::{
        INDEX_ENTRY_LEN, ValueRef,
        decode::{check_header, container_header, value_end},
        name_hash16, read_len, tag,
    },
    value::{Document, Value},
};

/// One path segment.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Segment {
    /// Field name (also the textual index).
    pub name: String,
    /// Array index, for unquoted canonical decimal segments.
    pub index: Option<usize>,
}

/// A parsed field path such as ``a.0.`my.field` ``.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FieldPath {
    segments: Vec<Segment>,
}

impl FieldPath {
    /// Parses dot notation; backticks quote a segment containing dots or spaces.
    ///
    /// # Errors
    /// [`DocError::InvalidFieldName`] (`RGN-1004`) for empty segments, unterminated backticks,
    /// NUL or segments longer than 1024 bytes.
    pub fn parse(path: &str) -> DocResult<Self> {
        let bad = |r: &str| DocError::InvalidFieldName(format!("bad path: {r}"));
        let mut segments = Vec::new();
        let mut rest = path;
        loop {
            let (seg, quoted, after) = if let Some(q) = rest.strip_prefix('`') {
                let close = q.find('`').ok_or_else(|| bad("unterminated backtick"))?;
                (&q[..close], true, &q[close + 1..])
            } else {
                let stop = rest.find('.').unwrap_or(rest.len());
                if rest[..stop].contains('`') {
                    return Err(bad("backtick inside a segment"));
                }
                (&rest[..stop], false, &rest[stop..])
            };
            if seg.is_empty() || seg.len() > MAX_FIELD_NAME_LEN || seg.contains('\0') {
                return Err(bad("empty, too long or NUL segment"));
            }
            let index = if quoted { None } else { canonical_index(seg) };
            segments.push(Segment {
                name: seg.to_owned(),
                index,
            });
            if after.is_empty() {
                break;
            }
            rest = after
                .strip_prefix('.')
                .ok_or_else(|| bad("expected '.' after a quoted segment"))?;
        }
        Ok(Self { segments })
    }

    /// A single-segment path naming a field (no parsing, no index interpretation).
    #[must_use]
    pub fn field(name: &str) -> Self {
        Self {
            segments: vec![Segment {
                name: name.to_owned(),
                index: None,
            }],
        }
    }

    /// Builds a path from segments (e.g. generated by code rather than typed by a user).
    #[must_use]
    pub fn from_segments(segments: Vec<Segment>) -> Self {
        Self { segments }
    }

    /// The segments.
    #[must_use]
    pub fn segments(&self) -> &[Segment] {
        &self.segments
    }
}

fn canonical_index(s: &str) -> Option<usize> {
    let canonical = s.bytes().all(|b| b.is_ascii_digit()) && (s == "0" || !s.starts_with('0'));
    if canonical { s.parse().ok() } else { None }
}

/// Looks up `path` in a decoded document; `None` = missing.
#[must_use]
pub fn get_path<'v>(doc: &'v Document, path: &FieldPath) -> Option<&'v Value> {
    let (first, rest) = path.segments.split_first()?;
    let mut cur = doc.get(&first.name)?;
    for seg in rest {
        cur = match cur {
            Value::Object(d) => d.get(&seg.name)?,
            Value::Array(items) => items.get(seg.index?)?,
            _ => return None,
        };
    }
    Some(cur)
}

/// A validated-header view over `RDoc` bytes supporting lazy lookups (O(depth · log fields)).
///
/// Only the header is checked up front; lookups bounds-check everything they touch and return
/// errors (never panic) on inconsistent bytes. Use [`crate::rdoc::decode`] to validate fully.
#[derive(Debug, Clone, Copy)]
pub struct RDocRef<'a> {
    bytes: &'a [u8],
}

impl<'a> RDocRef<'a> {
    /// Wraps `bytes` after checking the header and the root tag.
    ///
    /// # Errors
    /// As the header checks of [`crate::rdoc::decode`].
    pub fn new(bytes: &'a [u8]) -> DocResult<Self> {
        check_header(bytes)?;
        if bytes[crate::rdoc::HEADER_LEN] != tag::OBJECT {
            return Err(DocError::malformed(
                crate::rdoc::HEADER_LEN,
                "root is not an object",
            ));
        }
        Ok(Self { bytes })
    }

    /// The root object.
    ///
    /// # Errors
    /// [`DocError::Malformed`] if the root extent is inconsistent.
    pub fn root(&self) -> DocResult<ValueRef<'a>> {
        crate::rdoc::decode_value_ref(self.bytes, crate::rdoc::HEADER_LEN, self.bytes.len())
    }

    /// Looks up `path` without decoding siblings; `Ok(None)` = missing.
    ///
    /// # Errors
    /// [`DocError::Malformed`] if the bytes on the lookup path are inconsistent.
    pub fn get(&self, path: &FieldPath) -> DocResult<Option<ValueRef<'a>>> {
        let mut cur = self.root()?;
        for seg in &path.segments {
            let next = match cur.type_tag() {
                tag::OBJECT => object_field(cur, seg.name.as_bytes())?,
                tag::ARRAY => match seg.index {
                    Some(i) => array_element(cur, i)?,
                    None => None,
                },
                _ => None,
            };
            match next {
                Some(v) => cur = v,
                None => return Ok(None),
            }
        }
        Ok(Some(cur))
    }
}

/// Binary search of the object index by (hash, name bytes).
fn object_field<'a>(obj: ValueRef<'a>, name: &[u8]) -> DocResult<Option<ValueRef<'a>>> {
    let buf = obj.as_bytes();
    let end = buf.len();
    let h = container_header(buf, 1, end, tag::OBJECT, false)?;
    let target = (name_hash16(name), name);
    let (mut lo, mut hi) = (0usize, h.n);
    while lo < hi {
        let mid = lo + (hi - lo) / 2;
        let at = h.table_at + mid * INDEX_ENTRY_LEN;
        let hash = u16::from_le_bytes([buf[at], buf[at + 1]]);
        let offset = u32::from_le_bytes([buf[at + 2], buf[at + 3], buf[at + 4], buf[at + 5]]);
        let field_at = usize::try_from(offset)
            .ok()
            .and_then(|o| h.body_at.checked_add(o))
            .filter(|p| *p < h.body_end)
            .ok_or_else(|| DocError::malformed(at, "index offset out of range"))?;
        let (len, name_at) = read_len(buf, field_at, h.body_end, false)?;
        let name_end = crate::rdoc::checked_end(name_at, len, h.body_end)?;
        let entry_name = &buf[name_at..name_end];
        match (hash, entry_name).cmp(&target) {
            std::cmp::Ordering::Less => lo = mid + 1,
            std::cmp::Ordering::Greater => hi = mid,
            std::cmp::Ordering::Equal => {
                let stop = value_end(buf, name_end, h.body_end)?;
                return Ok(Some(ValueRef::new(&buf[name_end..stop])));
            }
        }
    }
    Ok(None)
}

/// Element `i` via the offset table.
fn array_element(arr: ValueRef<'_>, i: usize) -> DocResult<Option<ValueRef<'_>>> {
    let buf = arr.as_bytes();
    let h = container_header(buf, 1, buf.len(), tag::ARRAY, false)?;
    if i >= h.n {
        return Ok(None);
    }
    let at = h.table_at + i * crate::rdoc::ARRAY_OFFSET_LEN;
    let offset = u32::from_le_bytes([buf[at], buf[at + 1], buf[at + 2], buf[at + 3]]);
    let start = usize::try_from(offset)
        .ok()
        .and_then(|o| h.body_at.checked_add(o))
        .filter(|p| *p < h.body_end)
        .ok_or_else(|| DocError::malformed(at, "array offset out of range"))?;
    let stop = value_end(buf, start, h.body_end)?;
    Ok(Some(ValueRef::new(&buf[start..stop])))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn path_parse_dots_indexes_and_backticks() {
        let p = FieldPath::parse("a.0.`my.field`.01").unwrap();
        let names: Vec<&str> = p.segments().iter().map(|s| s.name.as_str()).collect();
        assert_eq!(names, ["a", "0", "my.field", "01"]);
        let idx: Vec<Option<usize>> = p.segments().iter().map(|s| s.index).collect();
        assert_eq!(idx, [None, Some(0), None, None]);
        assert!(
            FieldPath::parse("`0`").unwrap().segments()[0]
                .index
                .is_none()
        );
        for bad in ["", "a..b", "a.", ".a", "`a", "a`b", "`a`b", "a\0"] {
            assert!(FieldPath::parse(bad).is_err(), "{bad:?}");
        }
    }
}
