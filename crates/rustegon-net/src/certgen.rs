//! Certificate generation for `rustegon init` and `rustegon cert create-ca | create-node |
//! create-client` (FR-TLS-002, security.md §5).
//!
//! - CA: ECDSA P-256 (default) or Ed25519, valid 10 years, `pathLen = 0` (it signs leaves only;
//!   intermediates are not part of the model).
//! - Node certificate (node certificate format 2, ADR-035): ECDSA P-256, valid 1 year, SAN = the
//!   node's addresses (IP or DNS) + the URI [`NODE_ROLE_URI`] that `rustegon-security` maps to
//!   the `node` role (security.md §2), EKU serverAuth + clientAuth (a node is both server and
//!   client on the peer port). Format 1 certificates (node role as the EKU [`NODE_ROLE_OID`]) are
//!   no longer issued but still recognised by [`has_node_role`].
//! - Client certificate: ECDSA P-256, valid 1 year, CN = the identity mapped by X.509 auth,
//!   EKU clientAuth only (never the node role).
//!
//! Leaves default to P-256 even under an Ed25519 CA: Ed25519 end-entity certificates are not
//! accepted by every driver TLS stack (PD-046). Timestamps come from the sim-api [`Clock`] and
//! serial numbers from the sim-api [`Rng`]; key pairs are generated by `ring` from the OS
//! CSPRNG, which cannot be routed through a simulated RNG without weakening keys (PD-046).

use std::{fmt, path::Path, time::Duration};

use rcgen::{
    BasicConstraints, CertificateParams, DistinguishedName, DnType, ExtendedKeyUsagePurpose, IsCa,
    Issuer, KeyPair, KeyUsagePurpose, SanType, SerialNumber,
};
use rustegon_common::{
    Redacted,
    pki::{NODE_ROLE_OID, NODE_ROLE_URI},
};
use rustegon_sim_api::{Clock, FileSystem, OpenMode, Rng};
use rustls::pki_types::CertificateDer;
use time::OffsetDateTime;

use crate::TlsError;

/// CA validity (security.md §5: 10 years).
pub const CA_VALIDITY: Duration = Duration::from_hours(10 * 365 * 24);
/// Node and client certificate validity (security.md §5: 1 year).
pub const LEAF_VALIDITY: Duration = Duration::from_hours(365 * 24);
/// `notBefore` is backdated by this much so that a peer whose clock is slightly behind the
/// issuing host does not reject a freshly issued certificate as "not yet valid".
pub const NOT_BEFORE_BACKDATE: Duration = Duration::from_mins(5);

/// Signature key algorithm of a generated certificate.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub enum KeyAlgorithm {
    /// ECDSA on P-256 with SHA-256 (default; universally supported).
    #[default]
    EcdsaP256,
    /// Ed25519 (allowed for the CA by security.md §5).
    Ed25519,
}

impl KeyAlgorithm {
    fn rcgen(self) -> &'static rcgen::SignatureAlgorithm {
        match self {
            Self::EcdsaP256 => &rcgen::PKCS_ECDSA_P256_SHA256,
            Self::Ed25519 => &rcgen::PKCS_ED25519,
        }
    }
}

/// A generated certificate with its private key, both PEM.
#[derive(Clone)]
pub struct GeneratedCert {
    /// The certificate (PEM).
    pub cert_pem: String,
    /// The PKCS#8 private key (PEM). Secret.
    pub key_pem: Redacted<String>,
    /// `notAfter`, seconds since the Unix epoch.
    pub not_after_unix: i64,
}

impl fmt::Debug for GeneratedCert {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("GeneratedCert")
            .field("key_pem", &self.key_pem)
            .field("not_after_unix", &self.not_after_unix)
            .finish_non_exhaustive()
    }
}

impl GeneratedCert {
    /// Writes the certificate to `cert_path` and the key to `key_path`, both as new files
    /// (existing files are never overwritten; the caller decides about replacement). The key
    /// file is created owner-only ([`FileSystem::create_new_private`]: 0600 on Unix, directory
    /// ACL on Windows). Both files and their directories are synced.
    ///
    /// # Errors
    /// [`TlsError::Io`], including `AlreadyExists`.
    pub fn write_files(
        &self,
        fs: &dyn FileSystem,
        cert_path: &Path,
        key_path: &Path,
    ) -> Result<(), TlsError> {
        let mut key = fs
            .create_new_private(key_path)
            .map_err(|e| TlsError::io(key_path, e))?;
        key.append(self.key_pem.expose().as_bytes())
            .and_then(|()| key.sync_data())
            .map_err(|e| TlsError::io(key_path, e))?;
        let mut cert = fs
            .open(cert_path, OpenMode::CreateNew)
            .map_err(|e| TlsError::io(cert_path, e))?;
        cert.append(self.cert_pem.as_bytes())
            .and_then(|()| cert.sync_data())
            .map_err(|e| TlsError::io(cert_path, e))?;
        for path in [key_path, cert_path] {
            if let Some(dir) = path.parent().filter(|d| !d.as_os_str().is_empty()) {
                fs.sync_dir(dir).map_err(|e| TlsError::io(dir, e))?;
            }
        }
        Ok(())
    }
}

/// A CA able to issue node and client certificates.
pub struct CertAuthority {
    cert_pem: String,
    issuer: Issuer<'static, KeyPair>,
}

impl fmt::Debug for CertAuthority {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("CertAuthority").finish_non_exhaustive()
    }
}

impl CertAuthority {
    /// Generates a self-signed CA (`create-ca`, `init`). Returns the CA and its PEM pair for
    /// writing to disk.
    ///
    /// # Errors
    /// [`TlsError::Generate`].
    pub fn generate(
        common_name: &str,
        algorithm: KeyAlgorithm,
        clock: &dyn Clock,
        rng: &dyn Rng,
    ) -> Result<(Self, GeneratedCert), TlsError> {
        let key = KeyPair::generate_for(algorithm.rcgen())?;
        let mut params = base_params(common_name, CA_VALIDITY, clock, rng)?;
        params.is_ca = IsCa::Ca(BasicConstraints::Constrained(0));
        params.key_usages = vec![
            KeyUsagePurpose::KeyCertSign,
            KeyUsagePurpose::CrlSign,
            KeyUsagePurpose::DigitalSignature,
        ];
        let cert = params.self_signed(&key)?;
        let generated = GeneratedCert {
            cert_pem: cert.pem(),
            key_pem: Redacted::new(key.serialize_pem()),
            not_after_unix: params.not_after.unix_timestamp(),
        };
        let issuer = Issuer::new(params, key);
        Ok((
            Self {
                cert_pem: generated.cert_pem.clone(),
                issuer,
            },
            generated,
        ))
    }

    /// Loads an existing CA (`create-node`/`create-client` against the CA files written by
    /// `init`).
    ///
    /// # Errors
    /// [`TlsError::Generate`] when the certificate or key cannot be parsed.
    pub fn from_pem(cert_pem: &str, key_pem: &Redacted<String>) -> Result<Self, TlsError> {
        let key = KeyPair::from_pem(key_pem.expose())?;
        let issuer = Issuer::from_ca_cert_pem(cert_pem, key)?;
        Ok(Self {
            cert_pem: cert_pem.to_owned(),
            issuer,
        })
    }

    /// The CA certificate (PEM), to distribute as `ca_file`.
    #[must_use]
    pub fn cert_pem(&self) -> &str {
        &self.cert_pem
    }

    /// Issues a node certificate (`create-node`, `init`). `addresses` become the SAN entries
    /// (IP literals as IP SANs, everything else as DNS names); at least one is required because
    /// peers verify the SAN against the address they dial (security.md §5).
    ///
    /// # Errors
    /// [`TlsError::Config`] without addresses, [`TlsError::Generate`] for an invalid DNS name.
    pub fn issue_node(
        &self,
        node_name: &str,
        addresses: &[String],
        clock: &dyn Clock,
        rng: &dyn Rng,
    ) -> Result<GeneratedCert, TlsError> {
        if addresses.is_empty() {
            return Err(TlsError::Config(
                "a node certificate needs at least one address (SAN)".into(),
            ));
        }
        let mut params = base_params(node_name, LEAF_VALIDITY, clock, rng)?;
        params.subject_alt_names = CertificateParams::new(addresses.to_vec())?.subject_alt_names;
        // The node role is a URI SAN, not an EKU purpose (ADR-035): the former 2.25 UUID OID
        // made Go's crypto/x509 reject the whole certificate (PD-193).
        params
            .subject_alt_names
            .push(SanType::URI(NODE_ROLE_URI.try_into()?));
        params.extended_key_usages = vec![
            ExtendedKeyUsagePurpose::ServerAuth,
            ExtendedKeyUsagePurpose::ClientAuth,
        ];
        self.issue_leaf(params)
    }

    /// Issues a client certificate (`create-client`) whose subject CN is `common_name`; X.509
    /// authentication maps it to the user `x509:CN=<common_name>` (security.md §2).
    ///
    /// # Errors
    /// [`TlsError::Generate`].
    pub fn issue_client(
        &self,
        common_name: &str,
        clock: &dyn Clock,
        rng: &dyn Rng,
    ) -> Result<GeneratedCert, TlsError> {
        let mut params = base_params(common_name, LEAF_VALIDITY, clock, rng)?;
        params.extended_key_usages = vec![ExtendedKeyUsagePurpose::ClientAuth];
        self.issue_leaf(params)
    }

    fn issue_leaf(&self, mut params: CertificateParams) -> Result<GeneratedCert, TlsError> {
        params.is_ca = IsCa::ExplicitNoCa;
        params.key_usages = vec![KeyUsagePurpose::DigitalSignature];
        let key = KeyPair::generate_for(KeyAlgorithm::EcdsaP256.rcgen())?;
        let cert = params.signed_by(&key, &self.issuer)?;
        Ok(GeneratedCert {
            cert_pem: cert.pem(),
            key_pem: Redacted::new(key.serialize_pem()),
            not_after_unix: params.not_after.unix_timestamp(),
        })
    }
}

/// DER content octets of `id-kp-serverAuth` (1.3.6.1.5.5.7.3.1).
#[cfg(test)]
const KP_SERVER_AUTH: [u8; 8] = [0x2b, 0x06, 0x01, 0x05, 0x05, 0x07, 0x03, 0x01];

/// DER content octets (X.690 §8.19) of a dotted OID whose arcs fit in `u128` (enough for the
/// UUID arc `2.25.<uuid>`).
///
/// # Errors
/// [`TlsError::Config`] when the string is not a valid OID.
fn encode_oid(dotted: &str) -> Result<Vec<u8>, TlsError> {
    let bad = || TlsError::Config(format!("invalid OID {dotted:?}"));
    let arcs = dotted
        .split('.')
        .map(|a| a.parse::<u128>().map_err(|_| bad()))
        .collect::<Result<Vec<_>, _>>()?;
    let (first, second) = match arcs.as_slice() {
        [f @ 0..=1, s @ 0..=39, ..] | [f @ 2, s, ..] => (*f, *s),
        _ => return Err(bad()),
    };
    // X.690 §8.19.4: the first two arcs share one subidentifier, 40 * first + second.
    let head = second.checked_add(40 * first).ok_or_else(bad)?;
    let mut out = Vec::new();
    for arc in std::iter::once(head).chain(arcs[2..].iter().copied()) {
        // Base-128, most significant group first, continuation bit on all but the last.
        let mut groups = Vec::new();
        let mut v = arc;
        loop {
            groups.push(u8::try_from(v & 0x7f).unwrap_or(0));
            v >>= 7;
            if v == 0 {
                break;
            }
        }
        while let Some(g) = groups.pop() {
            out.push(if groups.is_empty() { g } else { g | 0x80 });
        }
    }
    Ok(out)
}

/// Whether a DER certificate was issued as a cluster node certificate: it carries the URI SAN
/// [`NODE_ROLE_URI`] (format 2) or, legacy format 1, the extended key usage purpose
/// [`NODE_ROLE_OID`] (ADR-035). Callers must verify the chain first; this only inspects the
/// extensions. The marker is trusted exactly as far as the CA that issued the certificate.
///
/// # Errors
/// [`TlsError::Certificate`] when the DER is not an X.509 certificate or its SAN or EKU
/// extension is malformed or repeated.
pub fn has_node_role(cert: &CertificateDer<'_>) -> Result<bool, TlsError> {
    let node_role = encode_oid(NODE_ROLE_OID)?;
    let (_, parsed) = x509_parser::parse_x509_certificate(cert.as_ref())
        .map_err(|e| TlsError::Certificate(e.to_string()))?;
    // `subject_alternative_name()` also rejects a repeated SAN extension.
    let san = parsed
        .subject_alternative_name()
        .map_err(|e| TlsError::Certificate(e.to_string()))?;
    let uri_role = san.is_some_and(|san| {
        san.value.general_names.iter().any(
            |n| matches!(n, x509_parser::extensions::GeneralName::URI(u) if *u == NODE_ROLE_URI),
        )
    });
    // `extended_key_usage()` also rejects a repeated EKU extension; its parsed purposes are not
    // used: x509-parser accepts an element whose tag carries the OID tag number in another class
    // (e.g. 0x46), which `rustegon-security` (x509-cert) does not read as a purpose, so the two
    // node-role checks disagreed (TC-SEC-010 fuzzing finding, PD-060). The raw extension value
    // is walked strictly instead.
    parsed
        .extended_key_usage()
        .map_err(|e| TlsError::Certificate(e.to_string()))?;
    let Some(ext) = parsed
        .extensions()
        .iter()
        .find(|e| e.oid.as_bytes() == EKU_OID)
    else {
        return Ok(uri_role);
    };
    // The EKU is walked even when the URI already matched, so a malformed one is still refused.
    // Compared on DER bytes: x509-parser renders arcs above u64 as hex, not as decimal.
    Ok(eku_purposes(ext.value)?.contains(&node_role.as_slice()) || uri_role)
}

/// 2.5.29.37 (id-ce-extKeyUsage), content octets.
const EKU_OID: [u8; 3] = [0x55, 0x1d, 0x25];

/// One DER TLV of `buf`: `(tag, content, rest)`; single-byte tags and definite minimal lengths
/// only (anything else is not DER).
fn read_der_tlv(buf: &[u8]) -> Option<(u8, &[u8], &[u8])> {
    let (&tag, rest) = buf.split_first()?;
    if tag & 0x1f == 0x1f {
        return None;
    }
    let (&first, rest) = rest.split_first()?;
    let (len, rest) = if first < 0x80 {
        (usize::from(first), rest)
    } else {
        let n = usize::from(first & 0x7f);
        if n == 0 || n > 4 || rest.len() < n || rest[0] == 0 {
            return None;
        }
        let len = rest[..n]
            .iter()
            .fold(0usize, |acc, &b| (acc << 8) | usize::from(b));
        if len < 0x80 {
            return None;
        }
        (len, &rest[n..])
    };
    (rest.len() >= len).then(|| (tag, &rest[..len], &rest[len..]))
}

/// The content octets of every purpose of an EKU extension value
/// (`SEQUENCE SIZE (1..MAX) OF OBJECT IDENTIFIER`, RFC 5280 §4.2.1.12).
fn eku_purposes(value: &[u8]) -> Result<Vec<&[u8]>, TlsError> {
    let bad = || TlsError::Certificate("malformed extended key usage".into());
    let (tag, mut content, rest) = read_der_tlv(value).ok_or_else(bad)?;
    if tag != 0x30 || !rest.is_empty() || content.is_empty() {
        return Err(bad());
    }
    let mut out = Vec::new();
    while !content.is_empty() {
        let (tag, oid, rest) = read_der_tlv(content).ok_or_else(bad)?;
        if tag != 0x06 || oid.is_empty() {
            return Err(bad());
        }
        out.push(oid);
        content = rest;
    }
    Ok(out)
}

/// Subject, validity and serial shared by all generated certificates.
fn base_params(
    common_name: &str,
    validity: Duration,
    clock: &dyn Clock,
    rng: &dyn Rng,
) -> Result<CertificateParams, TlsError> {
    let now = OffsetDateTime::from(clock.wall())
        .replace_nanosecond(0)
        .map_err(|e| TlsError::Config(e.to_string()))?;
    let mut params = CertificateParams::default();
    let mut dn = DistinguishedName::new();
    dn.push(DnType::CommonName, common_name);
    params.distinguished_name = dn;
    params.not_before = now - NOT_BEFORE_BACKDATE;
    params.not_after = now + validity;
    params.serial_number = Some(random_serial(rng));
    params.use_authority_key_identifier_extension = true;
    params.subject_alt_names = Vec::<SanType>::new();
    Ok(params)
}

/// A positive 128-bit serial (RFC 5280 §4.1.2.2: positive, at most 20 octets, unique per CA;
/// 127 random bits make collisions negligible). The top bit is cleared so the DER INTEGER is
/// positive without a padding byte, and a set second bit keeps the length fixed at 16 octets.
fn random_serial(rng: &dyn Rng) -> SerialNumber {
    let mut bytes = [0u8; 16];
    rng.fill_bytes(&mut bytes);
    bytes[0] = (bytes[0] & 0x7f) | 0x40;
    SerialNumber::from_slice(&bytes)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn encode_oid_matches_known_der() {
        assert_eq!(
            encode_oid("1.3.6.1.5.5.7.3.1").ok(),
            Some(KP_SERVER_AUTH.to_vec())
        );
        // X.667 Annex example-style check: 2.25.<128-bit> starts with 0x69 (2*40+25) and the
        // arc is base-128 encoded over 19 groups.
        let enc = encode_oid(NODE_ROLE_OID).unwrap_or_default();
        assert_eq!(enc.first(), Some(&0x69));
        assert_eq!(enc.len(), 1 + 19);
        assert!(enc[1..enc.len() - 1].iter().all(|b| b & 0x80 != 0));
        assert!(encode_oid("3.1").is_err());
        assert!(encode_oid("1.40").is_err());
        assert!(encode_oid("1.x").is_err());
    }
}
