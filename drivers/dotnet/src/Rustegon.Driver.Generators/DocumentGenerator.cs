using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Rustegon.Driver.Generators;

/// <summary>
/// Emits an <c>IRDocCodec&lt;T&gt;</c> for every <c>[RustegonDocument]</c> type of the compilation
/// and registers them from a module initializer (dotnet-driver.md §7, TC-DRV-NET-021). The
/// generated code calls only <c>RDocConverters</c> and <c>RDocMapping</c>: no reflection, so it is
/// trimming and AOT safe. The mapping rules are those documented on the driver's
/// <c>ReflectionCodec</c>; both must change together (the byte-identity tests catch a drift).
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class DocumentGenerator : IIncrementalGenerator
{
    private const string Mapping = "global::Rustegon.Driver.Mapping.";
    private const string Converters = Mapping + "RDocConverters.";
    private const string AttributeNamespace = "Rustegon.Driver.Mapping.";
    private const string DocumentAttribute = AttributeNamespace + "RustegonDocumentAttribute";

    private static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat;

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // The whole set is needed at once: a base type's codec dispatches to its derived types.
        IncrementalValueProvider<ImmutableArray<INamedTypeSymbol>> types = context.SyntaxProvider
            .ForAttributeWithMetadataName(DocumentAttribute, static (node, _) => node is TypeDeclarationSyntax, static (c, _) => (INamedTypeSymbol)c.TargetSymbol)
            .Collect();
        context.RegisterSourceOutput(types, static (spc, all) => Emit(spc, all));
    }

    /// <summary>
    /// The camelCase naming policy, identical to <c>System.Text.Json.JsonNamingPolicy.CamelCase</c>
    /// (which the reflection codec and <c>FieldPath</c> use; a property test compares the two).
    /// </summary>
    /// <param name="name">A member name.</param>
    /// <returns>The field name.</returns>
    public static string CamelCase(string name)
    {
        if (string.IsNullOrEmpty(name) || !char.IsUpper(name[0]))
        {
            return name;
        }

        char[] chars = name.ToCharArray();
        for (int i = 0; i < chars.Length; i++)
        {
            if (i == 1 && !char.IsUpper(chars[i]))
            {
                break;
            }

            bool hasNext = i + 1 < chars.Length;
            if (i > 0 && hasNext && !char.IsUpper(chars[i + 1]))
            {
                if (chars[i + 1] == ' ')
                {
                    chars[i] = char.ToLowerInvariant(chars[i]);
                }

                break;
            }

            chars[i] = char.ToLowerInvariant(chars[i]);
        }

        return new string(chars);
    }

    private static void Emit(SourceProductionContext spc, ImmutableArray<INamedTypeSymbol> found)
    {
        List<INamedTypeSymbol> all = [.. found.Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default)];
        var registered = new List<(string Type, string Codec)>();
        foreach (INamedTypeSymbol type in all.OrderBy(t => t.ToDisplayString(TypeFormat), StringComparer.Ordinal))
        {
            spc.CancellationToken.ThrowIfCancellationRequested();
            var diagnostics = new List<Diagnostic>();
            string? source = Generate(type, all, diagnostics, out string codec);
            foreach (Diagnostic d in diagnostics)
            {
                spc.ReportDiagnostic(d);
            }

            if (source is not null)
            {
                spc.AddSource(codec + ".g.cs", source);
                registered.Add((type.ToDisplayString(TypeFormat), codec));
            }
        }

        if (registered.Count == 0)
        {
            return;
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("namespace Rustegon.Driver.Generated");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>Registers the generated codecs of this assembly.</summary>");
        sb.AppendLine("    [global::System.CodeDom.Compiler.GeneratedCode(\"Rustegon.Driver.Generators\", \"1.0\")]");
        sb.AppendLine("    internal static class RustegonCodecRegistration");
        sb.AppendLine("    {");
        sb.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        sb.AppendLine("        internal static void Register()");
        sb.AppendLine("        {");
        foreach ((string type, string codec) in registered)
        {
            sb.Append("            ").Append(Mapping).Append("RDocCodecRegistry.Register<").Append(type).Append(">(").Append(codec).AppendLine(".Instance);");
        }

        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        spc.AddSource("RustegonCodecRegistration.g.cs", sb.ToString());
    }

    private static string? Generate(INamedTypeSymbol type, List<INamedTypeSymbol> all, List<Diagnostic> diagnostics, out string codec)
    {
        codec = "Codec_" + Mangle(type.ToDisplayString(TypeFormat));
        Location location = type.Locations.FirstOrDefault() ?? Location.None;
        string typeName = type.ToDisplayString(TypeFormat);
        if (type.IsGenericType)
        {
            diagnostics.Add(Diagnostic.Create(Diagnostics.InvalidType, location, type.Name, "generic types are not supported"));
            return null;
        }

        if (!IsAccessible(type))
        {
            diagnostics.Add(Diagnostic.Create(Diagnostics.InvalidType, location, type.Name, "it must be public or internal (and so must the types containing it)"));
            return null;
        }

        string? discriminator = Discriminator(type);
        List<INamedTypeSymbol> derived = [.. all
            .Where(t => !SymbolEqualityComparer.Default.Equals(t, type) && InheritsFrom(t, type) && Discriminator(t) is not null)
            .OrderByDescending(Depth)
            .ThenBy(t => t.ToDisplayString(TypeFormat), StringComparer.Ordinal)];
        string? duplicate = derived.Select(Discriminator).Append(discriminator).OfType<string>()
            .GroupBy(v => v, StringComparer.Ordinal).FirstOrDefault(g => g.Count() > 1)?.Key;
        if (duplicate is not null)
        {
            diagnostics.Add(Diagnostic.Create(Diagnostics.InvalidMapping, location, type.Name, "the discriminator '" + duplicate + "' is used twice"));
            return null;
        }

        var members = new List<Member>();
        IMethodSymbol? constructor = null;
        if (!type.IsAbstract)
        {
            List<IPropertySymbol> properties = Properties(type);
            constructor = Constructor(type, properties);
            if (constructor is null)
            {
                diagnostics.Add(Diagnostic.Create(Diagnostics.NoConstructor, location, type.Name));
                return null;
            }

            foreach (IPropertySymbol p in properties)
            {
                int bound = -1;
                for (int a = 0; a < constructor.Parameters.Length && bound < 0; a++)
                {
                    bound = string.Equals(constructor.Parameters[a].Name, p.Name, StringComparison.OrdinalIgnoreCase) ? a : -1;
                }

                bool settable = p.SetMethod is { DeclaredAccessibility: Accessibility.Public };
                if (bound < 0 && !settable)
                {
                    continue;
                }

                Kind kind = IsId(p) ? Kind.Id : Has(p, "RgnRevAttribute") ? Kind.Rev : Has(p, "RgnCounterAttribute") ? Kind.Counter : Kind.Normal;
                string? converter = MemberConverter(p, out string? why);
                if (converter is null)
                {
                    diagnostics.Add(Diagnostic.Create(Diagnostics.UnsupportedMember, p.Locations.FirstOrDefault() ?? location, type.Name, p.Name, p.Type.ToDisplayString(), why));
                    continue;
                }

                if (kind == Kind.Rev && p.Type.SpecialType != SpecialType.System_String)
                {
                    diagnostics.Add(Diagnostic.Create(Diagnostics.UnsupportedMember, p.Locations.FirstOrDefault() ?? location, type.Name, p.Name, p.Type.ToDisplayString(), "[RgnRev] needs a string"));
                    continue;
                }

                members.Add(new Member(
                    p.Name,
                    FieldName(p),
                    p.Type.WithNullableAnnotation(NullableAnnotation.NotAnnotated).ToDisplayString(TypeFormat),
                    converter,
                    kind,
                    Bound: bound));
            }

            string? dupField = members.GroupBy(m => m.Field, StringComparer.Ordinal).FirstOrDefault(g => g.Count() > 1)?.Key;
            if (dupField is not null)
            {
                diagnostics.Add(Diagnostic.Create(Diagnostics.InvalidMapping, location, type.Name, "two members use the field name '" + dupField + "'"));
            }
        }

        if (diagnostics.Count > 0)
        {
            return null;
        }

        return Source(type, typeName, codec, discriminator, derived, members, constructor);
    }

    private static string Source(INamedTypeSymbol type, string typeName, string codec, string? discriminator, List<INamedTypeSymbol> derived, List<Member> members, IMethodSymbol? constructor)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("namespace Rustegon.Driver.Generated");
        sb.AppendLine("{");
        sb.Append("    /// <summary>The RDoc codec of <see cref=\"").Append(typeName.Replace("global::", string.Empty)).AppendLine("\"/>.</summary>");
        sb.AppendLine("    [global::System.CodeDom.Compiler.GeneratedCode(\"Rustegon.Driver.Generators\", \"1.0\")]");
        sb.Append("    internal sealed class ").Append(codec).Append(" : ").Append(Mapping).Append("IRDocCodec<").Append(typeName).AppendLine(">");
        sb.AppendLine("    {");
        sb.Append("        internal static readonly ").Append(codec).Append(" Instance = new ").Append(codec).AppendLine("();");
        for (int i = 0; i < members.Count; i++)
        {
            sb.Append("        private static readonly ").Append(Mapping).Append("RDocConverter<").Append(members[i].Type).Append("> c").Append(Num(i))
                .Append(" = ").Append(members[i].Converter).AppendLine(";");
        }

        // Encode.
        sb.AppendLine();
        sb.Append("        public global::Rustegon.Driver.RDocument Encode(").Append(typeName).AppendLine(" value)");
        sb.AppendLine("        {");
        if (type.IsReferenceType)
        {
            sb.AppendLine("            global::System.ArgumentNullException.ThrowIfNull(value);");
        }

        for (int i = 0; i < derived.Count; i++)
        {
            string d = derived[i].ToDisplayString(TypeFormat);
            sb.Append("            if (value is ").Append(d).Append(" d").Append(Num(i)).Append(") return ").Append(Mapping).Append("RDocCodecRegistry.Get<").Append(d)
                .Append(">().Encode(d").Append(Num(i)).AppendLine(");");
        }

        sb.Append("            var document = new global::Rustegon.Driver.RDocument(").Append(Num(members.Count + 1)).AppendLine(");");
        // Field order (PD-108, as the Java mapper, PD-111): _id, the discriminator, then declaration order.
        for (int i = 0; i < members.Count; i++)
        {
            if (members[i].Kind == Kind.Id)
            {
                sb.Append("            ").Append(Mapping).Append("RDocMapping.WriteId(document, c").Append(Num(i)).Append(", value.").Append(members[i].Name).AppendLine(");");
            }
        }

        if (discriminator is not null)
        {
            sb.Append("            ").Append(Mapping).Append("RDocMapping.WriteDiscriminator(document, ").Append(Literal(discriminator)).AppendLine(");");
        }

        for (int i = 0; i < members.Count; i++)
        {
            Member m = members[i];
            if (m.Kind == Kind.Normal)
            {
                sb.Append("            ").Append(Mapping).Append("RDocMapping.Write(document, ").Append(Literal(m.Field)).Append(", c").Append(Num(i)).Append(", value.").Append(m.Name).AppendLine(");");
            }
        }

        sb.AppendLine("            return document;");
        sb.AppendLine("        }");

        // Decode.
        sb.AppendLine();
        sb.Append("        public ").Append(typeName).AppendLine(" Decode(global::Rustegon.Driver.RDocument document)");
        sb.AppendLine("        {");
        sb.AppendLine("            global::System.ArgumentNullException.ThrowIfNull(document);");
        if (discriminator is not null || derived.Count > 0)
        {
            sb.Append("            string discriminator = ").Append(Mapping).AppendLine("RDocMapping.ReadDiscriminator(document);");
            sb.Append("            if (discriminator != null").Append(discriminator is null ? string.Empty : " && discriminator != " + Literal(discriminator)).AppendLine(")");
            sb.AppendLine("            {");
            foreach (INamedTypeSymbol d in derived)
            {
                sb.Append("                if (discriminator == ").Append(Literal(Discriminator(d)!)).Append(") return ").Append(Mapping).Append("RDocCodecRegistry.Get<")
                    .Append(d.ToDisplayString(TypeFormat)).AppendLine(">().Decode(document);");
            }

            sb.Append("                throw ").Append(Mapping).Append("RDocMapping.UnknownDiscriminator(typeof(").Append(typeName).AppendLine("), discriminator);");
            sb.AppendLine("            }");
            sb.AppendLine();
        }

        if (type.IsAbstract)
        {
            sb.Append("            throw ").Append(Mapping).Append("RDocMapping.UnknownDiscriminator(typeof(").Append(typeName).AppendLine("), null);");
        }
        else
        {
            for (int i = 0; i < members.Count; i++)
            {
                sb.Append("            ").Append(members[i].Type).Append(" p").Append(Num(i)).Append(" = ").Append(Mapping).Append("RDocMapping.Read(document, ")
                    .Append(Literal(members[i].Field)).Append(", c").Append(Num(i)).AppendLine(", out _);");
            }

            var args = new List<string>();
            for (int a = 0; a < constructor!.Parameters.Length; a++)
            {
                int index = members.FindIndex(m => m.Bound == a);
                args.Add(index >= 0 ? "p" + Num(index) : "default(" + constructor.Parameters[a].Type.WithNullableAnnotation(NullableAnnotation.NotAnnotated).ToDisplayString(TypeFormat) + ")");
            }

            var inits = new List<string>();
            for (int i = 0; i < members.Count; i++)
            {
                // Every member not bound by the constructor is assigned: an absent field gives default (PD-108).
                if (members[i].Bound < 0)
                {
                    inits.Add(members[i].Name + " = p" + Num(i));
                }
            }

            sb.Append("            var result = new ").Append(typeName).Append('(').Append(string.Join(", ", args)).Append(')');
            sb.AppendLine(inits.Count == 0 ? ";" : " { " + string.Join(", ", inits) + " };");
            sb.AppendLine("            return result;");
        }

        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>Public instance properties with a public getter, base types first, declaration order, [RgnIgnore] excluded.</summary>
    private static List<IPropertySymbol> Properties(INamedTypeSymbol type)
    {
        var chain = new List<INamedTypeSymbol>();
        for (INamedTypeSymbol? t = type; t is not null && t.SpecialType is not (SpecialType.System_Object or SpecialType.System_ValueType); t = t.BaseType)
        {
            chain.Insert(0, t);
        }

        var order = new List<string>();
        var byName = new Dictionary<string, IPropertySymbol>(StringComparer.Ordinal);
        foreach (INamedTypeSymbol level in chain)
        {
            foreach (IPropertySymbol p in level.GetMembers().OfType<IPropertySymbol>())
            {
                if (p.IsStatic || p.IsIndexer || p.DeclaredAccessibility != Accessibility.Public || p.GetMethod is not { DeclaredAccessibility: Accessibility.Public }
                    || Has(p, "RgnIgnoreAttribute"))
                {
                    continue;
                }

                if (!byName.ContainsKey(p.Name))
                {
                    order.Add(p.Name);
                }

                byName[p.Name] = p;
            }
        }

        return [.. order.Select(n => byName[n])];
    }

    /// <summary>The public constructor with the most parameters that all match a property (name ignoring case, type).</summary>
    private static IMethodSymbol? Constructor(INamedTypeSymbol type, List<IPropertySymbol> properties)
    {
        IMethodSymbol? best = null;
        foreach (IMethodSymbol c in type.InstanceConstructors)
        {
            if (c.DeclaredAccessibility != Accessibility.Public || (best is not null && c.Parameters.Length <= best.Parameters.Length))
            {
                continue;
            }

            if (c.Parameters.All(q => properties.Any(p => string.Equals(p.Name, q.Name, StringComparison.OrdinalIgnoreCase) && SymbolEqualityComparer.Default.Equals(p.Type, q.Type))))
            {
                best = c;
            }
        }

        return best;
    }

    private static string? MemberConverter(IPropertySymbol p, out string? why)
    {
        why = null;
        ITypeSymbol t = p.Type;
        if (Has(p, "RgnCounterAttribute"))
        {
            why = "[RgnCounter] needs a long";
            return t.SpecialType == SpecialType.System_Int64 ? Converters + "Counter"
                : IsNullableOf(t, SpecialType.System_Int64) ? Converters + "Nullable(" + Converters + "Counter)"
                : null;
        }

        if (Has(p, "RgnGeoPointAttribute"))
        {
            why = "[RgnGeoPoint] needs a double[]";
            return t is IArrayTypeSymbol { Rank: 1, ElementType.SpecialType: SpecialType.System_Double } ? Converters + "GeoPoint" : null;
        }

        if (Attribute(p, "RgnVectorAttribute") is { } vector)
        {
            int dims = vector.ConstructorArguments.Length == 1 && vector.ConstructorArguments[0].Value is int d ? d : 0;
            why = "[RgnVector] needs a positive dimension count on a float[] or ReadOnlyMemory<float>";
            return dims <= 0 ? null
                : t is IArrayTypeSymbol { Rank: 1, ElementType.SpecialType: SpecialType.System_Single } ? Converters + "FixedVector(" + Num(dims) + ")"
                : IsMemoryOf(t, SpecialType.System_Single) ? Converters + "FixedVectorMemory(" + Num(dims) + ")"
                : null;
        }

        why = "the type has no RDoc mapping (dotnet-driver.md §7); nested types need [RustegonDocument]";
        return TypeConverter(t);
    }

    /// <summary>The converter expression of a member type (the reflection codec's <c>For</c>).</summary>
    private static string? TypeConverter(ITypeSymbol t)
    {
        if (t is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable)
        {
            return TypeConverter(nullable.TypeArguments[0]) is { } inner ? Converters + "Nullable(" + inner + ")" : null;
        }

        string? special = t.SpecialType switch
        {
            SpecialType.System_Boolean => "Boolean",
            SpecialType.System_Int64 => "Int64",
            SpecialType.System_Int32 => "Int32",
            SpecialType.System_Int16 => "Int16",
            SpecialType.System_Double => "Double",
            SpecialType.System_Single => "Single",
            SpecialType.System_Decimal => "Decimal",
            SpecialType.System_String => "String",
            SpecialType.System_DateTime => "DateTime",
            _ => null,
        };
        if (special is not null)
        {
            return Converters + special;
        }

        if (t is IArrayTypeSymbol { Rank: 1 } array)
        {
            return array.ElementType.SpecialType switch
            {
                SpecialType.System_Byte => Converters + "Binary",
                SpecialType.System_Single => Converters + "Vector",
                _ => TypeConverter(array.ElementType) is { } e ? Converters + "Array(" + e + ")" : null,
            };
        }

        if (t is not INamedTypeSymbol named)
        {
            return null;
        }

        if (IsMemoryOf(t, SpecialType.System_Byte))
        {
            return Converters + "BinaryMemory";
        }

        if (IsMemoryOf(t, SpecialType.System_Single))
        {
            return Converters + "VectorMemory";
        }

        string? known = MetadataName(named) switch
        {
            "System.DateTimeOffset" => "DateTimeOffset",
            "System.Guid" => "Guid",
            "Rustegon.Driver.ObjectId" => "ObjectId",
            "Rustegon.Driver.Decimal128" => "Decimal128",
            "Rustegon.Driver.RDocValue" => "Value",
            "Rustegon.Driver.RDocument" => "RawDocument",
            "Rustegon.Driver.RDocArray" => "RawArray",
            _ => null,
        };
        if (known is not null)
        {
            return Converters + known;
        }

        if (named.TypeKind == TypeKind.Enum)
        {
            return Converters + "Enum<" + named.ToDisplayString(TypeFormat) + ">()";
        }

        string generic = MetadataName(named.OriginalDefinition);
        if (generic == "System.Collections.Generic.List`1")
        {
            return TypeConverter(named.TypeArguments[0]) is { } e ? Converters + "List(" + e + ")" : null;
        }

        if (generic == "System.Collections.Generic.Dictionary`2" && named.TypeArguments[0].SpecialType == SpecialType.System_String)
        {
            return TypeConverter(named.TypeArguments[1]) is { } e ? Converters + "Dictionary(" + e + ")" : null;
        }

        return named.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == DocumentAttribute)
            ? Converters + "Document<" + named.WithNullableAnnotation(NullableAnnotation.NotAnnotated).ToDisplayString(TypeFormat) + ">()"
            : null;
    }

    private static string FieldName(IPropertySymbol p) =>
        IsId(p) ? "_id"
        : Has(p, "RgnRevAttribute") ? "_rev"
        : Attribute(p, "RgnFieldAttribute") is { ConstructorArguments.Length: 1 } field && field.ConstructorArguments[0].Value is string name ? name
        : CamelCase(p.Name);

    /// <summary>The discriminator value: the attribute's argument, else the simple type name (PD-110).</summary>
    private static string? Discriminator(INamedTypeSymbol t) =>
        t.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == AttributeNamespace + "RgnDiscriminatorAttribute") is not { } a ? null
        : a.ConstructorArguments.Length == 1 && a.ConstructorArguments[0].Value is string v ? v
        : t.Name;

    /// <summary>[RgnId], else a property named Id/id without [RgnField] (PD-108, as the Java mapper).</summary>
    private static bool IsId(IPropertySymbol p) =>
        Has(p, "RgnIdAttribute") || (p.Name is "Id" or "id" && !Has(p, "RgnFieldAttribute"));

    private static bool InheritsFrom(INamedTypeSymbol t, INamedTypeSymbol baseType)
    {
        for (INamedTypeSymbol? b = t.BaseType; b is not null; b = b.BaseType)
        {
            if (SymbolEqualityComparer.Default.Equals(b, baseType))
            {
                return true;
            }
        }

        return false;
    }

    private static int Depth(INamedTypeSymbol t)
    {
        int d = 0;
        for (INamedTypeSymbol? b = t.BaseType; b is not null; b = b.BaseType)
        {
            d++;
        }

        return d;
    }

    private static bool IsAccessible(INamedTypeSymbol type)
    {
        for (INamedTypeSymbol? t = type; t is not null; t = t.ContainingType)
        {
            if (t.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedOrInternal))
            {
                return false;
            }
        }

        return true;
    }

    private static bool IsNullableOf(ITypeSymbol t, SpecialType inner) =>
        t is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } n && n.TypeArguments[0].SpecialType == inner;

    private static bool IsMemoryOf(ITypeSymbol t, SpecialType element) =>
        t is INamedTypeSymbol { IsGenericType: true } n && MetadataName(n.OriginalDefinition) == "System.ReadOnlyMemory`1" && n.TypeArguments[0].SpecialType == element;

    private static string MetadataName(INamedTypeSymbol t) =>
        t.ContainingNamespace is { IsGlobalNamespace: false } ns ? ns.ToDisplayString() + "." + t.MetadataName : t.MetadataName;

    private static bool Has(ISymbol s, string attribute) => Attribute(s, attribute) is not null;

    private static AttributeData? Attribute(ISymbol s, string attribute) =>
        s.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == AttributeNamespace + attribute);

    private static string Literal(string s) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(s, quote: true);

    private static string Num(int i) => i.ToString(CultureInfo.InvariantCulture);

    private static string Mangle(string name)
    {
        var sb = new StringBuilder(name.Length);
        foreach (char c in name.Replace("global::", string.Empty))
        {
            // Escaped so that distinct names never collide: '_' → "_u", '.' → "_d", others → "_x".
            _ = char.IsLetterOrDigit(c) ? sb.Append(c) : sb.Append(c switch { '_' => "_u", '.' => "_d", _ => "_x" });
        }

        return sb.ToString();
    }

    private enum Kind
    {
        Normal,
        Id,
        Rev,
        Counter,
    }

    private sealed record Member(string Name, string Field, string Type, string Converter, Kind Kind, int Bound);
}
