using System;
using System.Collections.Generic;
using Rustegon.Driver.Mapping;

namespace Rustegon.Driver.MappedTypes;

/// <summary>Order states (stored as their names).</summary>
public enum OrderStatus
{
    /// <summary>New.</summary>
    New,

    /// <summary>Paid.</summary>
    Paid,

    /// <summary>Shipped.</summary>
    Shipped,
}

/// <summary>A mutable class with every scalar of the type mapping (dotnet-driver.md §7).</summary>
[RustegonDocument]
public sealed class AllTypes
{
    /// <summary>Id (null: generated by the server).</summary>
    [RgnId]
    public ObjectId? Id { get; set; }

    /// <summary>Server revision (read only).</summary>
    [RgnRev]
    public string? Rev { get; set; }

    /// <summary>bool.</summary>
    public bool Flag { get; set; }

    /// <summary>int64.</summary>
    public long Long { get; set; }

    /// <summary>int64.</summary>
    public int Int { get; set; }

    /// <summary>int64.</summary>
    public short Short { get; set; }

    /// <summary>float64.</summary>
    public double Double { get; set; }

    /// <summary>float64.</summary>
    public float Float { get; set; }

    /// <summary>decimal128.</summary>
    public decimal Money { get; set; }

    /// <summary>string.</summary>
    public string? Text { get; set; }

    /// <summary>binary.</summary>
    public byte[]? Bytes { get; set; }

    /// <summary>binary.</summary>
    public ReadOnlyMemory<byte> Memory { get; set; }

    /// <summary>datetime (UTC).</summary>
    public DateTime When { get; set; } = DateTime.UnixEpoch;

    /// <summary>datetime.</summary>
    public DateTimeOffset At { get; set; }

    /// <summary>uuid.</summary>
    public Guid Uuid { get; set; }

    /// <summary>objectId.</summary>
    public ObjectId Oid { get; set; }

    /// <summary>decimal128.</summary>
    public Decimal128 Dec { get; set; }

    /// <summary>vector_f32.</summary>
    public float[]? Vector { get; set; }

    /// <summary>vector_f32.</summary>
    public ReadOnlyMemory<float> VectorMemory { get; set; }

    /// <summary>Enum as string.</summary>
    public OrderStatus Status { get; set; }

    /// <summary>Nullable value type.</summary>
    public int? MaybeInt { get; set; }

    /// <summary>Nullable enum.</summary>
    public OrderStatus? MaybeStatus { get; set; }

    /// <summary>Explicit field name.</summary>
    [RgnField("custom_name")]
    public string? Renamed { get; set; }

    /// <summary>Not stored.</summary>
    [RgnIgnore]
    public string? Ignored { get; set; }

    /// <summary>Computed (get-only, not stored).</summary>
    public int TextLength => Text?.Length ?? 0;

    /// <summary>List of strings.</summary>
    public List<string>? Tags { get; set; }

    /// <summary>Array of int64.</summary>
    public long[]? Numbers { get; set; }

    /// <summary>Dictionary.</summary>
    public Dictionary<string, double>? Scores { get; set; }

    /// <summary>Nested document.</summary>
    public Address? Address { get; set; }

    /// <summary>List of nested documents.</summary>
    public List<Line>? Lines { get; set; }

    /// <summary>Schemaless sub-document.</summary>
    public RDocument? Extra { get; set; }

    /// <summary>Any value.</summary>
    public RDocValue Any { get; set; } = RDocValue.Null;
}

/// <summary>A nested record with a primary constructor.</summary>
/// <param name="Street">Street.</param>
/// <param name="City">City.</param>
[RustegonDocument]
public sealed record Address(string Street, string City)
{
    /// <summary>Init-only member outside the constructor.</summary>
    public string? Zip { get; init; }
}

/// <summary>A nested struct.</summary>
[RustegonDocument]
public struct Line
{
    /// <summary>Sku.</summary>
    public string Sku { get; set; }

    /// <summary>Quantity.</summary>
    public int Qty { get; set; }
}

/// <summary>A typed order (record with id, rev, enum, nested list, vector and geo point).</summary>
/// <param name="Id">Id.</param>
/// <param name="Status">Status.</param>
/// <param name="Total">Total.</param>
[RustegonDocument]
public sealed record Order([property: RgnId] long Id, OrderStatus Status, decimal Total)
{
    /// <summary>Revision.</summary>
    [RgnRev]
    public string? Rev { get; init; }

    /// <summary>Lines.</summary>
    public List<Line> Lines { get; init; } = [];

    /// <summary>Embedding.</summary>
    [RgnVector(3)]
    public float[]? Embedding { get; init; }

    /// <summary>Location.</summary>
    [RgnGeoPoint]
    public double[]? Location { get; init; }

    /// <summary>Counter projection.</summary>
    [RgnCounter]
    public long Views { get; set; }

    /// <summary>Required member.</summary>
    public required string Customer { get; init; }
}

/// <summary>Polymorphic base.</summary>
[RustegonDocument]
public abstract class Shape
{
    /// <summary>Id.</summary>
    [RgnId]
    public string? Id { get; set; }

    /// <summary>Name.</summary>
    public string? Name { get; set; }
}

/// <summary>A circle.</summary>
[RustegonDocument]
[RgnDiscriminator("circle")]
public sealed class Circle : Shape
{
    /// <summary>Radius.</summary>
    public double Radius { get; set; }
}

/// <summary>A rectangle (itself a base).</summary>
[RustegonDocument]
[RgnDiscriminator("rect")]
public class Rect : Shape
{
    /// <summary>Width.</summary>
    public double Width { get; set; }

    /// <summary>Height.</summary>
    public double Height { get; set; }
}

/// <summary>A square (two levels down).</summary>
[RustegonDocument]
[RgnDiscriminator("square")]
public sealed class Square : Rect
{
    /// <summary>Rounded corners.</summary>
    public bool Rounded { get; set; }
}

/// <summary>A drawing holding shapes of any kind.</summary>
[RustegonDocument]
public sealed class Drawing
{
    /// <summary>Shapes.</summary>
    public List<Shape>? Shapes { get; set; }

    /// <summary>Optional main shape.</summary>
    public Shape? Main { get; set; }
}

/// <summary>Self-referencing tree.</summary>
[RustegonDocument]
public sealed class TreeNode
{
    /// <summary>Label.</summary>
    public string? Label { get; set; }

    /// <summary>Children.</summary>
    public List<TreeNode>? Children { get; set; }
}

/// <summary>A shape whose discriminator defaults to its simple name ("Triangle").</summary>
[RustegonDocument]
[RgnDiscriminator]
public sealed class Triangle : Shape
{
    /// <summary>Side.</summary>
    public double Side { get; set; }
}

/// <summary>Id by convention: a property named Id without attributes maps to <c>_id</c> and is written first.</summary>
[RustegonDocument]
public sealed class Note
{
    /// <summary>Body (declared before the id on purpose).</summary>
    public string? Body { get; set; }

    /// <summary>Id.</summary>
    public string? Id { get; set; }
}
