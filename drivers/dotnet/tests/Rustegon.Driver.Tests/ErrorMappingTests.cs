    [GeneratedRegex(@"^\s*-\s*code:\s*(\d+)")]
    private static partial Regex CodeLine();

    [GeneratedRegex(@"^\s+(name|grpc|http|retryable|internal):\s*""?([^""\s]+)""?\s*$")]
    private static partial Regex FieldLine();

    private static string ErrorsJson => Path.Combine(TestPaths.Conformance, "generated", "errors.json");

    private static JsonDocument LoadErrorsJson() => JsonDocument.Parse(File.ReadAllText(ErrorsJson));

    private static List<Dictionary<string, string>> ParseErrorsYaml()
    {
        var entries = new List<Dictionary<string, string>>();
        foreach (string line in File.ReadAllLines(TestPaths.ErrorsYaml))
        {
            Match m = CodeLine().Match(line);
            if (m.Success)
            {
                entries.Add(new Dictionary<string, string> { ["code"] = m.Groups[1].Value });
                continue;
            }

            Match f = FieldLine().Match(line);
            if (f.Success && entries.Count > 0)
            {
                entries[^1][f.Groups[1].Value] = f.Groups[2].Value;
            }
        }

        return entries;
    }

    [Fact]
    public void tc_drv_net_006_error_table_matches_errors_yaml()
    {
        // The table is generated by crates/rustegon-common/tests/driver_tables.rs, which fails when
        // it is stale; this check guards the compiled file against a missed re-bless (PD-075).
        List<Dictionary<string, string>> yaml = ParseErrorsYaml();
        Assert.Equal(yaml.Count, ErrorCodes.All.Count);
        foreach ((Dictionary<string, string> y, ErrorCodeInfo c) in yaml.Zip(ErrorCodes.All))
        {
            Assert.Equal(int.Parse(y["code"]), c.Code);
            Assert.Equal(y["name"], c.Name);
            Assert.Equal(y["grpc"], c.GrpcStatusName);
            Assert.Equal(int.Parse(y["http"]), c.HttpStatus);
            Assert.Equal(y["retryable"], c.Retryable.ToString().ToLowerInvariant());
            Assert.Equal(y.ContainsKey("internal"), c.Internal);
        }
    }

