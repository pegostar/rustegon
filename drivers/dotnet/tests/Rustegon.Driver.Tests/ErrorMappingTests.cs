    [Fact]
    public void tc_drv_net_006_error_detail_is_read_from_the_status_trailer()
    {
        var detail = new ErrorDetail
        {
            Code = 4003,
            Name = "RateLimited",
            Retryable = true,
            TraceId = "4bf92f3577b34da6a3ce929d0e0e4736",
            RetryAfterMs = 250,
            Details = { ["scope"] = "login" },
        };
        var status = new Google.Rpc.Status
        {
            Code = (int)StatusCode.ResourceExhausted,
            Message = "too many requests",
            Details = { Any.Pack(detail) },
        };
        RpcException rpc = status.ToRpcException();
        var e = Assert.IsType<RateLimitedException>(ErrorMapper.FromRpcException(rpc));
        Assert.Equal(4003, e.Code);
        Assert.Equal("RateLimited", e.Name);
        Assert.True(e.IsRetryable);
        Assert.Null(e.Committed);
        Assert.Equal("login", e.Details["scope"]);
        Assert.Equal("4bf92f3577b34da6a3ce929d0e0e4736", e.TraceId);
        Assert.Equal(TimeSpan.FromMilliseconds(250), e.RetryAfter);
        Assert.Equal("too many requests", e.Message);
        Assert.Same(rpc, e.InnerException);

        var commit = new ErrorDetail { Code = 2006, Name = "CommitOutcomeUnknown", Committed = false };
        var s2 = new Google.Rpc.Status { Code = (int)StatusCode.Unknown, Message = "unknown", Details = { Any.Pack(commit) } };
        Assert.False(Assert.IsType<CommitOutcomeUnknownException>(ErrorMapper.FromRpcException(s2.ToRpcException())).Committed);
    }

