    /// <summary>checkErrorMapping, one case per catalog code: class of errors.json, code and name.</summary>
    [Theory]
    [MemberData(nameof(CatalogCodes))]
    public void tc_drv_net_006_conformance_error_mapping_code(int code)
    {
        using JsonDocument json = LoadErrorsJson();
        JsonElement entry = json.RootElement.GetProperty("codes").EnumerateArray().Single(e => e.GetProperty("code").GetInt32() == code);
        string expected = entry.GetProperty("exception").GetProperty("dotnet").GetString()!;
        var detail = new ErrorDetail { Code = (uint)code, Name = entry.GetProperty("name").GetString()!, Retryable = true, Committed = true };
        RustegonException e = ErrorMapper.Create(ErrorMapper.FromDetail(detail), "m");
        Assert.Equal(expected, e.GetType().Name);
        Assert.Equal(code, e.Code);
        Assert.Equal(detail.Name, e.Name);

        // errors-map.yaml rules: the flags come from the response, never from the table.
        Assert.True(e.IsRetryable);
        Assert.True(e.Committed);
    }

