    /// <summary>checkErrorMapping, one case per transport fallback: a bare status maps to its class, code and flag.</summary>
    [Theory]
    [MemberData(nameof(TransportStatuses))]
    public void tc_drv_net_006_conformance_transport_fallback(string grpcStatusName)
    {
        using JsonDocument json = LoadErrorsJson();
        JsonElement entry = json.RootElement.GetProperty("transport").EnumerateArray().Single(e => e.GetProperty("grpc").GetString() == grpcStatusName);

        // `default` stands for every status without its own entry: check each of them.
        StatusCode[] statuses = grpcStatusName == "default"
            ? [.. System.Enum.GetValues<StatusCode>().Where(s => s != StatusCode.OK
                && ErrorCodes.TransportFallbacks.All(f => f.GrpcStatusName != ErrorCatalog.GoogleRpcName(s)))]
            : [.. System.Enum.GetValues<StatusCode>().Where(s => ErrorCatalog.GoogleRpcName(s) == grpcStatusName)];
        Assert.NotEmpty(statuses);
        foreach (StatusCode status in statuses)
        {
            RustegonException e = ErrorMapper.FromRpcException(new RpcException(new Status(status, "x")));
            Assert.Equal(entry.GetProperty("exception").GetProperty("dotnet").GetString(), e.GetType().Name);
            Assert.Equal(entry.GetProperty("code").GetInt32(), e.Code);
            Assert.Equal(entry.GetProperty("retryable").GetBoolean(), e.IsRetryable);
        }
    }

    [Fact]
    public void tc_drv_net_006_hierarchy_matches_errors_map_classes()
    {
        using JsonDocument json = LoadErrorsJson();
        JsonElement[] classes = [.. json.RootElement.GetProperty("classes").EnumerateArray()];
        Dictionary<string, string> dotnetById = classes.ToDictionary(c => c.GetProperty("id").GetString()!, c => c.GetProperty("dotnet").GetString()!);
        System.Type[] exported = typeof(RustegonException).Assembly.GetExportedTypes();
        foreach (JsonElement c in classes)
        {
            string name = c.GetProperty("dotnet").GetString()!;
            System.Type type = Assert.Single(exported, t => t.Name == name && typeof(RustegonException).IsAssignableFrom(t));
            JsonElement parent = c.GetProperty("parent");
            if (parent.ValueKind == JsonValueKind.Null)
            {
                Assert.Equal(typeof(RustegonException), type);
            }
            else
            {
                Assert.Equal(dotnetById[parent.GetString()!], type.BaseType!.Name);
            }
        }
    }

