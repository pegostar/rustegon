/// <summary>
/// TC-DRV-NET-021 (FR-DRV-001): the <c>[RustegonDocument]</c> source generator driven by
/// <see cref="CSharpGeneratorDriver"/>: the emitted code (snapshot), that it compiles without
/// errors or warnings, the build errors for unmappable types, and the module-initializer
/// registration. That the generated code is clean under the trimming and AOT analyzers is the
/// build of <c>tests/Rustegon.Driver.MappedTypes</c> (<c>IsAotCompatible</c>, warnings as errors).
/// </summary>
public sealed class MappingGeneratorTests
{
    private static readonly MetadataReference[] References = [.. ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!)
        .Split(Path.PathSeparator)
        .Where(p => p.Length > 0)
        .Append(typeof(RDocument).Assembly.Location)
        .Distinct(StringComparer.OrdinalIgnoreCase)
        .Select(p => MetadataReference.CreateFromFile(p))];

    private static (Compilation Output, ImmutableArray<Diagnostic> Diagnostics, GeneratorDriverRunResult Run) Generate(string source)
    {
        var compilation = CSharpCompilation.Create(
            "Gen" + Guid.NewGuid().ToString("N"),
            [CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.Latest))],
            References,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
        GeneratorDriver driver = CSharpGeneratorDriver.Create(new DocumentGenerator());
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out Compilation output, out ImmutableArray<Diagnostic> diagnostics, TestContext.Current.CancellationToken);
        return (output, diagnostics, driver.GetRunResult());
    }

    private static string Source(GeneratorDriverRunResult run, string hint) =>
        run.Results.Single().GeneratedSources.Single(s => s.HintName == hint).SourceText.ToString().ReplaceLineEndings("\n");

    [Fact]
    public void tc_drv_net_021_generated_codec_snapshot()
    {
        (Compilation output, ImmutableArray<Diagnostic> diagnostics, GeneratorDriverRunResult run) = Generate("""
            using Rustegon.Driver.Mapping;
            namespace Shop;
            [RustegonDocument]
            public sealed record Item([property: RgnId] string Sku, int Qty)
            {
                [RgnRev] public string? Rev { get; init; }
                [RgnField("p")] public decimal Price { get; set; }
                [RgnIgnore] public string? Note { get; set; }
                public int Twice => Qty * 2;
            }
            """);
        Assert.Empty(diagnostics);
        Assert.Empty(output.GetDiagnostics(TestContext.Current.CancellationToken).Where(d => d.Severity >= DiagnosticSeverity.Warning));
        Assert.Equal(
            """
            // <auto-generated/>
            namespace Rustegon.Driver.Generated
            {
                /// <summary>The RDoc codec of <see cref="Shop.Item"/>.</summary>
                [global::System.CodeDom.Compiler.GeneratedCode("Rustegon.Driver.Generators", "1.0")]
                internal sealed class Codec_Shop_dItem : global::Rustegon.Driver.Mapping.IRDocCodec<global::Shop.Item>
                {
                    internal static readonly Codec_Shop_dItem Instance = new Codec_Shop_dItem();
                    private static readonly global::Rustegon.Driver.Mapping.RDocConverter<string> c0 = global::Rustegon.Driver.Mapping.RDocConverters.String;
                    private static readonly global::Rustegon.Driver.Mapping.RDocConverter<int> c1 = global::Rustegon.Driver.Mapping.RDocConverters.Int32;
                    private static readonly global::Rustegon.Driver.Mapping.RDocConverter<string> c2 = global::Rustegon.Driver.Mapping.RDocConverters.String;
                    private static readonly global::Rustegon.Driver.Mapping.RDocConverter<decimal> c3 = global::Rustegon.Driver.Mapping.RDocConverters.Decimal;

                    public global::Rustegon.Driver.RDocument Encode(global::Shop.Item value)
                    {
                        global::System.ArgumentNullException.ThrowIfNull(value);
                        var document = new global::Rustegon.Driver.RDocument(5);
                        global::Rustegon.Driver.Mapping.RDocMapping.WriteId(document, c0, value.Sku);
                        global::Rustegon.Driver.Mapping.RDocMapping.Write(document, "qty", c1, value.Qty);
                        global::Rustegon.Driver.Mapping.RDocMapping.Write(document, "p", c3, value.Price);
                        return document;
                    }

                    public global::Shop.Item Decode(global::Rustegon.Driver.RDocument document)
                    {
                        global::System.ArgumentNullException.ThrowIfNull(document);
                        string p0 = global::Rustegon.Driver.Mapping.RDocMapping.Read(document, "_id", c0, out _);
                        int p1 = global::Rustegon.Driver.Mapping.RDocMapping.Read(document, "qty", c1, out _);
                        string p2 = global::Rustegon.Driver.Mapping.RDocMapping.Read(document, "_rev", c2, out _);
                        decimal p3 = global::Rustegon.Driver.Mapping.RDocMapping.Read(document, "p", c3, out _);
                        var result = new global::Shop.Item(p0, p1) { Rev = p2, Price = p3 };
                        return result;
                    }
                }
            }

            """,
            Source(run, "Codec_Shop_dItem.g.cs"));
        Assert.Contains(
            "global::Rustegon.Driver.Mapping.RDocCodecRegistry.Register<global::Shop.Item>(Codec_Shop_dItem.Instance);",
            Source(run, "RustegonCodecRegistration.g.cs"),
            StringComparison.Ordinal);
        Assert.Contains("[global::System.Runtime.CompilerServices.ModuleInitializer]", Source(run, "RustegonCodecRegistration.g.cs"), StringComparison.Ordinal);
    }

    [Fact]
    public void tc_drv_net_021_every_supported_shape_compiles_cleanly()
    {
        (Compilation output, ImmutableArray<Diagnostic> diagnostics, GeneratorDriverRunResult run) = Generate("""
            using System;
            using System.Collections.Generic;
            using Rustegon.Driver;
            using Rustegon.Driver.Mapping;
            namespace M;
            public enum Color { Red, Green }
            [RustegonDocument] public struct P { public int X { get; set; } }
            [RustegonDocument] public class Outer
            {
                [RustegonDocument] public sealed class Inner { public string? S { get; set; } }
            }
            [RustegonDocument] public sealed class All
            {
                [RgnId] public Guid? Id { get; set; }
                public bool B { get; set; } public long L { get; set; } public int I { get; set; } public short S { get; set; }
                public double D { get; set; } public float F { get; set; } public decimal M { get; set; } public string? T { get; set; }
                public byte[]? Bin { get; set; } public ReadOnlyMemory<byte> BinM { get; set; }
                public DateTime Dt { get; set; } public DateTimeOffset Dto { get; set; } public Guid G { get; set; }
                public ObjectId O { get; set; } public Decimal128 D128 { get; set; } public float[]? V { get; set; }
                public ReadOnlyMemory<float> VM { get; set; } [RgnVector(4)] public ReadOnlyMemory<float> V4 { get; set; }
                public Color C { get; set; } public Color? NC { get; set; } public int? NI { get; set; }
                public List<P>? LP { get; set; } public P[]? AP { get; set; } public Dictionary<string, List<int?>>? Map { get; set; }
                public Outer.Inner? Nested { get; set; } public RDocument? Raw { get; set; } public RDocArray? RawA { get; set; }
                public RDocValue Any { get; set; } [RgnGeoPoint] public double[]? Where { get; set; }
                [RgnCounter] public long? Hits { get; set; } public required string Req { get; init; }
            }
            """);
        Assert.Empty(diagnostics);
        Assert.Empty(output.GetDiagnostics(TestContext.Current.CancellationToken).Where(d => d.Severity >= DiagnosticSeverity.Warning));
        Assert.Equal(5, run.Results.Single().GeneratedSources.Length); // 4 codecs + registration
    }

    [Theory]
    [InlineData("public System.Collections.Generic.IList<int>? Xs { get; set; }", "RGNG001")]
    [InlineData("public System.Uri? Link { get; set; }", "RGNG001")]
    [InlineData("public Plain? Other { get; set; }", "RGNG001")]
    [InlineData("[RgnVector(3)] public double[]? V { get; set; }", "RGNG001")]
    [InlineData("[RgnVector(0)] public float[]? V { get; set; }", "RGNG001")]
    [InlineData("[RgnGeoPoint] public float[]? G { get; set; }", "RGNG001")]
    [InlineData("[RgnCounter] public int C { get; set; }", "RGNG001")]
    [InlineData("[RgnRev] public long R { get; set; }", "RGNG001")]
    [InlineData("public System.Collections.Generic.Dictionary<int, int>? D { get; set; }", "RGNG001")]
    [InlineData("[RgnField(\"a\")] public int A1 { get; set; } [RgnField(\"a\")] public int A2 { get; set; }", "RGNG003")]
    [InlineData("[RgnId] public int A1 { get; set; } [RgnId] public int A2 { get; set; }", "RGNG003")]
    public void tc_drv_net_021_unmappable_members_fail_the_build(string member, string id)
    {
        (_, ImmutableArray<Diagnostic> diagnostics, GeneratorDriverRunResult run) = Generate($$"""
            using Rustegon.Driver.Mapping;
            public sealed class Plain { }
            [RustegonDocument] public sealed class Doc { {{member}} }
            """);
        Diagnostic d = Assert.Single(diagnostics);
        Assert.Equal(id, d.Id);
        Assert.Equal(DiagnosticSeverity.Error, d.Severity);
        Assert.DoesNotContain(run.Results.Single().GeneratedSources, s => s.HintName.StartsWith("Codec_", StringComparison.Ordinal));
    }

    [Theory]
    [InlineData("[RustegonDocument] public sealed class Doc { public Doc(int other) { } public int A { get; set; } }", "RGNG002")]
    [InlineData("[RustegonDocument] public sealed class Doc<T> { public int A { get; set; } }", "RGNG004")]
    [InlineData("public static class Host { [RustegonDocument] private sealed class Doc { public int A { get; set; } } }", "RGNG004")]
    [InlineData("[RustegonDocument] public abstract class B { } [RustegonDocument, RgnDiscriminator(\"x\")] public sealed class C1 : B { } [RustegonDocument, RgnDiscriminator(\"x\")] public sealed class C2 : B { }", "RGNG003")]
    public void tc_drv_net_021_unmappable_types_fail_the_build(string types, string id)
    {
        (_, ImmutableArray<Diagnostic> diagnostics, _) = Generate("using Rustegon.Driver.Mapping;\n" + types);
        Assert.Contains(diagnostics, d => d.Id == id && d.Severity == DiagnosticSeverity.Error);
    }

    [Fact]
    public void tc_drv_net_021_codecs_of_another_assembly_register_through_its_module_initializer()
    {
        // MappedTypes is a separate assembly: referencing Order as a type argument does not run its
        // module initializer; the registry runs it on first lookup.
        IRDocCodec<MappedTypes.Order> codec = RDocCodecRegistry.Get<MappedTypes.Order>();
        Assert.Equal("Codec_Rustegon_dDriver_dMappedTypes_dOrder", codec.GetType().Name);
        Assert.Equal("Rustegon.Driver.MappedTypes", codec.GetType().Assembly.GetName().Name);
        Assert.Equal("Codec_Rustegon_dDriver_dTests_dMapping_dLocalDoc", RDocCodecRegistry.Get<LocalDoc>().GetType().Name);
    }

    [Fact]
    public void tc_drv_net_021_camel_case_equals_system_text_json()
    {
        foreach (string name in new[] { "Id", "ID", "URLValue", "XMLHttpRequest", "already", "A", "AB", "ABc", "IOStream", "Snake_Case", "Ünicode", "X1Y", "Big Space" })
        {
            Assert.Equal(System.Text.Json.JsonNamingPolicy.CamelCase.ConvertName(name), DocumentGenerator.CamelCase(name));
        }
    }

    [FsCheck.Xunit.Property(MaxTest = 500)]
    public bool tc_drv_net_021_camel_case_property(FsCheck.NonEmptyString name) =>
        System.Text.Json.JsonNamingPolicy.CamelCase.ConvertName(name.Get) == DocumentGenerator.CamelCase(name.Get);

    [Fact]
    public void tc_drv_net_021_generator_is_packed_as_an_analyzer()
    {
        // The driver project packs the generator under analyzers/dotnet/cs; the assembly must be
        // the netstandard2.0 build a compiler can load.
        Assembly generator = typeof(DocumentGenerator).Assembly;
        Assert.Contains(generator.GetCustomAttributes<System.Runtime.Versioning.TargetFrameworkAttribute>(), a => a.FrameworkName.StartsWith(".NETStandard,Version=v2.0", StringComparison.Ordinal));
        string csproj = File.ReadAllText(Path.Combine(TestPaths.Repo, "drivers", "dotnet", "src", "Rustegon.Driver", "Rustegon.Driver.csproj"));
        Assert.Contains("PackagePath=\"analyzers/dotnet/cs\"", csproj, StringComparison.Ordinal);
    }
}

