// Writes src/errors/codes.generated.ts from drivers/conformance/generated/errors.json (PD-075):
// the Node driver does not edit the shared tables, it derives its own from the generated JSON.
// `--check` fails when the checked-in file is stale (run by the unit tests too).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const source = path.join(root, '..', 'conformance', 'generated', 'errors.json');
const target = path.join(root, 'src', 'errors', 'codes.generated.ts');

export function render(json) {
  const lines = [
    '// GENERATED by scripts/generate-errors.mjs from drivers/conformance/generated/errors.json - do not edit.',
    '// Regenerate: npm run generate:errors (PD-075).',
    '',
    '/** One catalog code: its name, the class id of errors-map.yaml and its gRPC status. */',
    'export interface CodeEntry {',
    '  readonly name: string;',
    '  readonly classId: string;',
    '  readonly grpc: string;',
    '}',
    '',
    '/** A failure without ErrorDetail, by gRPC status name (errors-map.yaml `transport`). */',
    'export interface TransportFallback {',
    '  readonly classId: string;',
    '  readonly code: number;',
    '  readonly retryable: boolean;',
    '}',
    '',
    'export const CODES: ReadonlyMap<number, CodeEntry> = new Map<number, CodeEntry>([',
  ];
  for (const c of json.codes) {
    lines.push(
      `  [${c.code}, { name: ${JSON.stringify(c.name)}, classId: ${JSON.stringify(c.exception.id)}, grpc: ${JSON.stringify(c.grpc)} }],`,
    );
  }
  lines.push(']);', '', 'export const TRANSPORT: ReadonlyMap<string, TransportFallback> = new Map<string, TransportFallback>([');
  for (const t of json.transport) {
    lines.push(
      `  [${JSON.stringify(t.grpc)}, { classId: ${JSON.stringify(t.exception.id)}, code: ${t.code}, retryable: ${t.retryable} }],`,
    );
  }
  lines.push(']);', '', `export const UNKNOWN_CLASS_ID = ${JSON.stringify(json.unknown.id)};`, '');
  return lines.join('\n');
}

const text = render(JSON.parse(readFileSync(source, 'utf8')));
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== text) {
    console.error(`${target} is stale: run npm run generate:errors`);
    process.exit(1);
  }
} else {
  writeFileSync(target, text);
}
