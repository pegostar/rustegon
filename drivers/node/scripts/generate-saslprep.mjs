// Writes src/auth/saslprep-tables.generated.ts (RFC 3454 A.1) from the .NET driver's generated
// table, itself extracted from the Rust stringprep crate the server uses, so every driver refuses
// exactly the same unassigned code points.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const source = path.join(root, '..', 'dotnet', 'src', 'Rustegon.Driver', 'Auth', 'SaslPrepTables.g.cs');
const target = path.join(root, 'src', 'auth', 'saslprep-tables.generated.ts');

const pairs = [...readFileSync(source, 'utf8').matchAll(/^\s*(0x[0-9A-F]+), (0x[0-9A-F]+),\s*$/gm)].map((m) => `  ${m[1]}, ${m[2]},`);
if (pairs.length === 0) {
  throw new Error(`no ranges found in ${source}`);
}
writeFileSync(
  target,
  [
    '// GENERATED by scripts/generate-saslprep.mjs from drivers/dotnet/src/Rustegon.Driver/Auth/SaslPrepTables.g.cs - do not edit.',
    '// RFC 3454 Table A.1 (unassigned code points in Unicode 3.2) as inclusive start/end pairs, sorted;',
    '// originally from the Rust stringprep crate 0.1.5 used by the server.',
    '',
    'export const UNASSIGNED_RANGES: readonly number[] = [',
    ...pairs,
    '];',
    '',
  ].join('\n'),
);
