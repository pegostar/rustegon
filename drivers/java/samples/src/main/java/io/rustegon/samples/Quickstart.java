package io.rustegon.samples;

import io.rustegon.driver.Cursor;
import io.rustegon.driver.Filters;
import io.rustegon.driver.RustegonClient;
import io.rustegon.driver.RustegonClientSettings;
import io.rustegon.driver.RustegonCollection;
import io.rustegon.driver.RustegonCredential;
import io.rustegon.driver.RustegonDatabase;
import io.rustegon.driver.Sorts;
import io.rustegon.driver.TlsSettings;
import io.rustegon.driver.TransactionOptions;
import io.rustegon.driver.Updates;
import io.rustegon.samples.model.Order;
import io.rustegon.samples.model.Order_;
import java.math.BigDecimal;
import java.nio.file.Path;
import java.time.Duration;
import java.time.Instant;
import java.util.Optional;

/**
 * The quick start of drivers/java/README.md (java-driver.md §2–§4), compiled by the build so
 * that the documented code cannot drift from the API (AC-DRV-002).
 *
 * <p>Usage: {@code Quickstart <host:port> <user> [<ca.crt>]}; the password is read from the
 * environment variable {@code RUSTEGON_PASSWORD} (never from the command line). Plain text
 * unless the CA of a node with TLS is given (ADR-034).
 */
public final class Quickstart {
    private Quickstart() {}

    /**
     * Connects, writes and reads a few orders, and runs a transaction.
     *
     * @param args endpoint, user, optional CA certificate file
     */
    public static void main(String[] args) {
        if (args.length < 2 || args.length > 3 || System.getenv("RUSTEGON_PASSWORD") == null) {
            System.err.println("usage: Quickstart <host:port> <user> [<ca.crt>] "
                    + "(password in RUSTEGON_PASSWORD)");
            System.exit(2);
        }
        RustegonClientSettings settings = RustegonClientSettings.builder()
                .endpoints(args[0])
                .credential(RustegonCredential.scram(args[1],
                        System.getenv("RUSTEGON_PASSWORD").toCharArray()))
                // A node with security.tls = true (always in a cluster): trust its CA.
                .tls(args.length == 3
                        ? TlsSettings.builder().caCertificate(Path.of(args[2])).build()
                        : TlsSettings.disabled())
                .defaultDatabase("shop")
                .applicationName("rustegon-quickstart")
                .build();
        try (RustegonClient client = RustegonClient.create(settings)) {
            client.createDatabase("shop");
            RustegonDatabase db = client.database("shop");
            db.createCollection("orders");
            RustegonCollection<Order> orders = db.collection("orders", Order.class);

            orders.insertOne(new Order("o-1", null, "paid", new BigDecimal("120.00"),
                    Instant.now()));
            Optional<Order> o = orders.findById("o-1");
            System.out.println("found: " + o.orElseThrow());

            // Order_ is the metamodel generated by rustegon-processor.
            try (Cursor<Order> c = orders.find(Filters.eq(Order_.status, "paid")
                            .and(Filters.gte(Order_.total, new BigDecimal("100"))))
                    .sort(Sorts.desc(Order_.createdAt)).limit(50).cursor()) {
                for (Order x : c) {
                    System.out.println(x.id() + " " + x.total());
                }
            }

            // withTransaction retries the whole callback on retryable failures (§4).
            long updated = client.withTransaction(
                    TransactionOptions.serializable().maxRetryTime(Duration.ofMinutes(2)),
                    txn -> txn.collection("shop.orders", Order.class)
                            .updateOne(Filters.id("o-1"), Updates.set(Order_.status, "shipped"))
                            .modifiedCount());
            System.out.println("updated: " + updated);
        }
    }
}
