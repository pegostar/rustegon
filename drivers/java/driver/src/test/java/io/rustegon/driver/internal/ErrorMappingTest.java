/**
 * TC-DRV-JAVA-006: the error table and the exception mapping (FR-DRV-002, java-driver.md §6,
 * protocol.md §3/§7, PD-075). The compiled table ({@link ErrorCodes}, generated by the Rust test
 * {@code driver_tables.rs}) equals {@code proto/errors.yaml} entry by entry and, once the
 * conformance suite is present, {@code drivers/conformance/errors-map.yaml} (classes, hierarchy,
 * unknown-code and transport fallbacks); {@code ErrorDetail} packed in {@code google.rpc.Status}
 * (exactly as {@code rustegon_proto::status::to_status} sends it) becomes the right exception
 * with every field; failures without a detail use the transport fallbacks; an interrupted caller
 * gets a {@link CancellationException}.
 */
public class ErrorMappingTest {
    private static final String EXCEPTION_PACKAGE = "io.rustegon.driver.";

    @SuppressWarnings("unchecked")
    private static Map<String, Object> yaml(Path file) throws IOException {
        return (Map<String, Object>) new Load(LoadSettings.builder().build())
                .loadFromString(Files.readString(file));
    }

    private static Optional<Path> conformanceFile(String relative) {
        return TestPaths.conformance().map(p -> p.resolve(relative)).filter(Files::isRegularFile);
    }

    @Test
    @SuppressWarnings("unchecked")
    void tc_drv_java_006_table_matches_errors_yaml() throws IOException {
        List<Map<String, Object>> codes = (List<Map<String, Object>>)
                yaml(TestPaths.repoRoot().resolve("proto/errors.yaml")).get("codes");
        assertEquals(codes.size(), ErrorCodes.all().size(), "number of codes");
        for (int i = 0; i < codes.size(); i++) {
            Map<String, Object> c = codes.get(i);
            ErrorCodes.Info e = ErrorCodes.all().get(i);
            String where = "code " + c.get("code");
            assertEquals(((Number) c.get("code")).intValue(), e.code(), where);
            assertEquals(c.get("name"), e.name(), where);
            assertEquals(c.getOrDefault("aliases", List.of()), e.aliases(), where);
            assertEquals(c.get("grpc"), e.grpcStatusName(), where);
            // The gRPC code name and number of the table agree with io.grpc.
            assertEquals(Status.Code.valueOf(e.grpcStatusName()).value(), e.grpcStatusCode(),
                    where);
            assertEquals(((Number) c.get("http")).intValue(), e.httpStatus(), where);
            assertEquals(String.valueOf(c.get("retryable")).toUpperCase(),
                    e.retryable().name(), where);
            assertEquals(c.get("retry_note"), e.retryNote(), where);
            assertEquals(Boolean.TRUE.equals(c.get("internal")), e.internal(), where);
            assertEquals(e, ErrorCodes.find(e.code()), where);
        }
        assertNull(ErrorCodes.find(9999));
    }

    @Test
    @SuppressWarnings("unchecked")
    public void tc_drv_java_006_conformance_errors_map() throws Exception {
        Optional<Path> file = conformanceFile("errors-map.yaml");
        Assumptions.assumeTrue(file.isPresent(),
                "drivers/conformance/errors-map.yaml not merged yet (lane DK, PD-075)");
        Map<String, Object> root = yaml(file.get());
        List<String> failures = new ArrayList<>();
        // Class ids → Java class names, and the hierarchy of the Java classes.
        Map<String, String> javaName = new HashMap<>();
        List<Map<String, Object>> classes = (List<Map<String, Object>>) root.get("classes");
        for (Map<String, Object> c : classes) {
            javaName.put((String) c.get("id"), (String) c.get("java"));
        }
        for (Map<String, Object> c : classes) {
            Class<?> cls = Class.forName(EXCEPTION_PACKAGE + c.get("java"));
            Object parent = c.get("parent");
            Class<?> want = parent == null ? RuntimeException.class
                    : Class.forName(EXCEPTION_PACKAGE + javaName.get((String) parent));
            if (cls.getSuperclass() != want) {
                failures.add(c.get("java") + " extends " + cls.getSuperclass().getSimpleName()
                        + ", errors-map.yaml says " + want.getSimpleName());
            }
        }
        // Every catalog code: the class thrown for it.
        Map<Integer, String> codes = (Map<Integer, String>) root.get("codes");
        assertEquals(ErrorCodes.all().size(), codes.size(), "codes in errors-map.yaml");
        for (Map.Entry<Integer, String> e : codes.entrySet()) {
            String want = javaName.get(e.getValue());
            String got = mapped(e.getKey()).getClass().getSimpleName();
            if (!want.equals(got)) {
                failures.add("RGN-" + e.getKey() + " -> " + got + ", errors-map.yaml says "
                        + want);
            }
        }
        // Codes unknown to the driver.
        assertEquals(javaName.get((String) root.get("unknown")),
                ErrorMapper.create("x", error(424242, "Future"), null).getClass()
                        .getSimpleName());
        // Failures without ErrorDetail, for every gRPC status.
        Map<String, Map<String, Object>> transport =
                (Map<String, Map<String, Object>>) root.get("transport");
        for (Status.Code grpc : Status.Code.values()) {
            if (grpc == Status.Code.OK) {
                continue;
            }
            Map<String, Object> want = transport.getOrDefault(grpc.name(),
                    transport.get("default"));
            RustegonException got = ErrorMapper.map(Status.fromCode(grpc).asRuntimeException());
            if (!javaName.get((String) want.get("class")).equals(got.getClass().getSimpleName())
                    || ((Number) want.get("code")).intValue() != got.code()
                    || !want.get("retryable").equals(got.isRetryable())) {
                failures.add("transport " + grpc + " -> " + got.getClass().getSimpleName() + " "
                        + got.code() + " retryable=" + got.isRetryable()
                        + ", errors-map.yaml says " + want);
            }
        }
        assertTrue(failures.isEmpty(), String.join("\n", failures));
    }

    private static RustegonError error(int code, String name) {
        return new RustegonError(code, name, false, null, Map.of(), "", null);
    }

    private static StatusRuntimeException failure(Status.Code grpc, ErrorDetail detail) {
        com.google.rpc.Status status = com.google.rpc.Status.newBuilder()
                .setCode(grpc.value())
                .setMessage("server message")
                .addDetails(Any.pack(detail))
                .build();
        return StatusProto.toStatusRuntimeException(status);
    }

    private static RustegonException mapped(int code) {
        ErrorCodes.Info info = ErrorCodes.find(code);
        return ErrorMapper.map(failure(Status.Code.valueOf(info.grpcStatusName()),
                ErrorDetail.newBuilder().setCode(code).setName(info.name()).build()));
    }

    @Test
    void tc_drv_java_006_detail_fields_are_carried() {
        ErrorDetail d = ErrorDetail.newBuilder()
                .setCode(2006).setName("CommitOutcomeUnknown").setRetryable(false)
                .setCommitted(true).putDetails("txn", "abc").setTraceId("0af7651916cd43dd")
                .setRetryAfterMs(250).build();
        RustegonException e = ErrorMapper.map(failure(Status.Code.UNKNOWN, d));
        assertInstanceOf(CommitOutcomeUnknownException.class, e);
        assertEquals(2006, e.code());
        assertEquals("CommitOutcomeUnknown", e.name());
        assertFalse(e.isRetryable());
        assertEquals(Boolean.TRUE, e.committed().orElseThrow());
        assertEquals(Map.of("txn", "abc"), e.details());
        assertEquals("0af7651916cd43dd", e.traceId());
        assertEquals(Duration.ofMillis(250), e.retryAfter().orElseThrow());
        assertEquals("server message", e.getMessage());
        assertInstanceOf(StatusRuntimeException.class, e.getCause());
        RustegonException plain = mapped(1001);
        assertTrue(plain.committed().isEmpty());
        assertTrue(plain.retryAfter().isEmpty());
        // The retry flag is the response's, never the catalog default: RGN-2001 is "yes" in the
        // catalog, but this response does not set it.
        assertFalse(mapped(2001).isRetryable());
        RustegonException retryable = ErrorMapper.map(failure(Status.Code.ABORTED,
                ErrorDetail.newBuilder().setCode(2002).setName("TransactionAborted")
                        .setRetryable(true).build()));
        assertTrue(retryable.isRetryable());
    }

    @Test
    void tc_drv_java_006_every_code_maps_to_its_exception() {
        // The class named by the table, for every code (so the factory knows every name).
        for (ErrorCodes.Info c : ErrorCodes.all()) {
            RustegonException e = mapped(c.code());
            assertEquals(c.exceptionType(), e.getClass().getSimpleName(), "RGN-" + c.code());
            assertEquals(c.code(), e.code());
            assertEquals(c.name(), e.name());
        }
        // Spot checks of java-driver.md §6, independent of the table.
        Map<Integer, Class<? extends RustegonException>> expected = Map.ofEntries(
                Map.entry(1001, RustegonClientException.class),
                Map.entry(1005, DuplicateKeyException.class),
                Map.entry(1006, DocumentValidationException.class),
                Map.entry(1010, QuerySyntaxException.class),
                Map.entry(1011, QuerySyntaxException.class),
                Map.entry(1012, QuerySyntaxException.class),
                Map.entry(2001, TransactionConflictException.class),
                Map.entry(2002, TransactionAbortedException.class),
                Map.entry(2006, CommitOutcomeUnknownException.class),
                Map.entry(2003, RustegonTimeoutException.class),
                Map.entry(5006, RustegonTimeoutException.class),
                Map.entry(3002, UnavailableException.class),
                Map.entry(4001, AuthenticationException.class),
                Map.entry(4002, AuthorizationException.class),
                Map.entry(4003, RateLimitedException.class),
                Map.entry(5001, RustegonServerException.class));
        expected.forEach((code, cls) -> assertEquals(cls, mapped(code).getClass(),
                "RGN-" + code));
        // Hierarchy (PD-075, PD-076).
        assertEquals(RustegonClientException.class, QuerySyntaxException.class.getSuperclass());
        assertEquals(AuthenticationException.class,
                PasswordChangeRequiredException.class.getSuperclass());
        // A code unknown to this driver (newer server): base class, code and name kept.
        RustegonException unknown = ErrorMapper.map(failure(Status.Code.FAILED_PRECONDITION,
                ErrorDetail.newBuilder().setCode(1099).setName("SomethingNew").build()));
        assertEquals(RustegonException.class, unknown.getClass());
        assertEquals(1099, unknown.code());
        assertEquals("SomethingNew", unknown.name());
    }

    @Test
    void tc_drv_java_006_failures_without_detail_use_the_transport_fallbacks() {
        RustegonException unavailable =
                ErrorMapper.map(Status.UNAVAILABLE.withDescription("io").asRuntimeException());
        assertInstanceOf(UnavailableException.class, unavailable);
        assertEquals(3002, unavailable.code());
        assertTrue(unavailable.isRetryable());
        RustegonException timeout = ErrorMapper.map(Status.DEADLINE_EXCEEDED.asRuntimeException());
        assertInstanceOf(RustegonTimeoutException.class, timeout);
        assertEquals(5006, timeout.code());
        assertFalse(timeout.isRetryable());
        assertInstanceOf(AuthenticationException.class,
                ErrorMapper.map(Status.UNAUTHENTICATED.asRuntimeException()));
        RustegonException exhausted =
                ErrorMapper.map(Status.RESOURCE_EXHAUSTED.asRuntimeException());
        assertEquals(5004, exhausted.code());
        assertTrue(exhausted.isRetryable());
        // Any other status: RGN-5001 Internal, not retryable.
        RustegonException other = ErrorMapper.map(Status.DATA_LOSS.asRuntimeException());
        assertInstanceOf(RustegonServerException.class, other);
        assertEquals(5001, other.code());
        assertEquals("Internal", other.name());
        // A details trailer holding something else than ErrorDetail is ignored.
        com.google.rpc.Status notDetail = com.google.rpc.Status.newBuilder()
                .setCode(Status.Code.UNAVAILABLE.value())
                .addDetails(Any.pack(com.google.rpc.Status.getDefaultInstance())).build();
        assertEquals(3002,
                ErrorMapper.map(StatusProto.toStatusRuntimeException(notDetail)).code());
        // A corrupt details trailer is ignored as well.
        Metadata trailers = new Metadata();
        trailers.put(ErrorMapper.STATUS_DETAILS, new byte[] {0x1a, 0x7f, 0x01});
        assertEquals(5001, ErrorMapper.map(Status.INTERNAL.asRuntimeException(trailers)).code());
    }

    @Test
    void tc_drv_java_006_interrupted_callers_get_a_cancellation() {
        StatusRuntimeException interrupted = Status.CANCELLED
                .withDescription("Thread interrupted")
                .withCause(new InterruptedException()).asRuntimeException();
        assertTrue(ErrorMapper.isCallerCancellation(interrupted));
        try {
            CancellationException c = ErrorMapper.cancelled("the call", interrupted);
            assertEquals(interrupted, c.getCause());
            // The interrupt flag is kept for the caller.
            assertTrue(Thread.currentThread().isInterrupted());
        } finally {
            Thread.interrupted();
        }
        // A server-side cancellation is a server error (the default fallback), not the caller's.
        StatusRuntimeException server = Status.CANCELLED.asRuntimeException();
        assertFalse(ErrorMapper.isCallerCancellation(server));
        assertInstanceOf(RustegonServerException.class, ErrorMapper.map(server));
    }
}
