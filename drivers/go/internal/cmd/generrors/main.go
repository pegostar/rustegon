// Command generrors writes errorcodes_gen.go from drivers/conformance/generated/errors.json, the
// shared error table of all drivers (PD-075). The JSON file has no Go column: the Go driver uses
// the language-neutral class ids of errors-map.yaml as its ErrorClass names.
//
// Usage: go run ./internal/cmd/generrors <errors.json> <out.go>
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"
)

type exception struct {
	ID string `json:"id"`
}

type code struct {
	Code      int       `json:"code"`
	Name      string    `json:"name"`
	Aliases   []string  `json:"aliases"`
	Internal  bool      `json:"internal"`
	Grpc      string    `json:"grpc"`
	GrpcCode  int       `json:"grpcCode"`
	HTTP      int       `json:"http"`
	Retryable string    `json:"retryable"`
	Exception exception `json:"exception"`
}

type transport struct {
	Code      int       `json:"code"`
	Grpc      string    `json:"grpc"`
	Retryable bool      `json:"retryable"`
	Exception exception `json:"exception"`
}

type class struct {
	ID     string  `json:"id"`
	Parent *string `json:"parent"`
}

type table struct {
	Classes   []class     `json:"classes"`
	Codes     []code      `json:"codes"`
	Transport []transport `json:"transport"`
	Unknown   exception   `json:"unknown"`
}

// grpcNames maps google.rpc.Code names to grpc-go codes constants.
var grpcNames = map[string]string{
	"OK": "OK", "CANCELLED": "Canceled", "UNKNOWN": "Unknown", "INVALID_ARGUMENT": "InvalidArgument",
	"DEADLINE_EXCEEDED": "DeadlineExceeded", "NOT_FOUND": "NotFound", "ALREADY_EXISTS": "AlreadyExists",
	"PERMISSION_DENIED": "PermissionDenied", "RESOURCE_EXHAUSTED": "ResourceExhausted",
	"FAILED_PRECONDITION": "FailedPrecondition", "ABORTED": "Aborted", "OUT_OF_RANGE": "OutOfRange",
	"UNIMPLEMENTED": "Unimplemented", "INTERNAL": "Internal", "UNAVAILABLE": "Unavailable",
	"DATA_LOSS": "DataLoss", "UNAUTHENTICATED": "Unauthenticated",
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: generrors <errors.json> <out.go>")
		os.Exit(2)
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		fail(err)
	}
	var t table
	if err := json.Unmarshal(raw, &t); err != nil {
		fail(err)
	}
	sort.Slice(t.Codes, func(i, j int) bool { return t.Codes[i].Code < t.Codes[j].Code })
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/cmd/generrors from drivers/conformance/generated/errors.json. DO NOT EDIT.\n")
	b.WriteString("// Regenerate with scripts/generate.sh (PD-075).\n\npackage rustegon\n\nimport \"google.golang.org/grpc/codes\"\n\n")
	b.WriteString("// Error codes of the catalog (protocol.md §7, proto/errors.yaml): RGN-<code>.\nconst (\n")
	for _, c := range t.Codes {
		fmt.Fprintf(&b, "\t// Code%s is RGN-%d (%s).\n\tCode%s = %d\n", c.Name, c.Code, c.Grpc, c.Name, c.Code)
		for _, a := range c.Aliases {
			fmt.Fprintf(&b, "\t// Code%s is an alias of Code%s.\n\tCode%s = %d\n", a, c.Name, a, c.Code)
		}
	}
	b.WriteString(")\n\n")
	b.WriteString("// classParents is the class hierarchy of errors-map.yaml.\nvar classParents = map[ErrorClass]ErrorClass{\n")
	for _, c := range t.Classes {
		if c.Parent != nil {
			fmt.Fprintf(&b, "\tClass%s: Class%s,\n", c.ID, *c.Parent)
		}
	}
	b.WriteString("}\n\n")
	b.WriteString("// catalog joins every code with its name, catalog retry class and error class.\nvar catalog = map[int32]catalogEntry{\n")
	for _, c := range t.Codes {
		fmt.Fprintf(&b, "\t%d: {name: %q, retryable: %q, internal: %t, class: Class%s},\n", c.Code, c.Name, c.Retryable, c.Internal, c.Exception.ID)
	}
	b.WriteString("}\n\n")
	b.WriteString("// unknownCodeClass is the class of a code this driver does not know (newer server).\n")
	fmt.Fprintf(&b, "const unknownCodeClass = Class%s\n\n", t.Unknown.ID)
	b.WriteString("// transportFallbacks maps a failure without ErrorDetail by gRPC status; codes.Unknown is also\n// the entry used for statuses not listed (\"default\").\nvar transportFallbacks = map[codes.Code]transportEntry{\n")
	var deflt *transport
	for i, tr := range t.Transport {
		if tr.Grpc == "default" {
			deflt = &t.Transport[i]
			continue
		}
		g, ok := grpcNames[tr.Grpc]
		if !ok {
			fail(fmt.Errorf("unknown gRPC status %s", tr.Grpc))
		}
		fmt.Fprintf(&b, "\tcodes.%s: {code: %d, retryable: %t, class: Class%s},\n", g, tr.Code, tr.Retryable, tr.Exception.ID)
	}
	b.WriteString("}\n\n")
	if deflt == nil {
		fail(fmt.Errorf("no default transport entry"))
	}
	fmt.Fprintf(&b, "// transportDefault applies to gRPC statuses without their own entry.\nvar transportDefault = transportEntry{code: %d, retryable: %t, class: Class%s}\n", deflt.Code, deflt.Retryable, deflt.Exception.ID)
	ids := make([]string, 0, len(t.Classes))
	for _, c := range t.Classes {
		ids = append(ids, "Class"+c.ID)
	}
	fmt.Fprintf(&b, "\n// allClasses lists the classes of errors-map.yaml in file order.\nvar allClasses = []ErrorClass{%s}\n", strings.Join(ids, ", "))
	if err := os.WriteFile(os.Args[2], b.Bytes(), 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "generrors:", err)
	os.Exit(1)
}
