/// Asserts that no secret reached `rustegond`'s output, log files or audit files.
fn assert_not_in_node_output(env: &Env, daemon_output: &str, secrets: &[&str]) {
    for secret in secrets {
        assert!(
            !daemon_output.contains(secret),
            "a secret reached rustegond's stdout/stderr"
        );
        for sub in ["logs", "audit"] {
            let hits = files_containing(&env.data_dir().join(sub), secret);
            assert!(hits.is_empty(), "a secret reached {hits:?}");
        }
    }
}

/// Audit records (JSON lines) of the node.
fn audit_records(env: &Env) -> Vec<Json> {
    files_under(&env.data_dir().join("audit"))
        .iter()
        .flat_map(|(_, bytes)| {
            String::from_utf8_lossy(bytes)
                .lines()
                .filter_map(|l| serde_json::from_str::<Json>(l).ok())
                .collect::<Vec<_>>()
        })
        .collect()
}

/// A random 256-bit KEK as 64 hex digits (the `storage.encryption_key_file` format).
fn random_kek_hex() -> String {
    let word = || OsRng.next_u64();
    format!(
        "{:016x}{:016x}{:016x}{:016x}",
        word(),
        word(),
        word(),
        word()
    )
}

/// Writes a KEK file readable by the owner only.
fn kek_file(env: &Env, name: &str, hex: &str) -> String {
    let path = env.path(name);
    StdFileSystem
        .create_new_private(&path)
        .and_then(|mut f| f.append(format!("{hex}\n").as_bytes()))
        .unwrap();
    path.display().to_string()
}

/// Is `path` one of several names of the same file (a hard link)?
fn is_hard_linked(path: &Path) -> bool {
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt as _;
        std::fs::metadata(path).unwrap().nlink() >= 2
    }
    #[cfg(windows)]
    {
        // `MetadataExt::number_of_links` is unstable; `fsutil hardlink list` prints one line per
        // name of the file and needs no elevation.
        let out = std::process::Command::new("fsutil")
            .args(["hardlink", "list"])
            .arg(path)
            .output()
            .unwrap();
        assert!(out.status.success(), "fsutil: {out:?}");
        String::from_utf8_lossy(&out.stdout)
            .lines()
            .filter(|l| !l.trim().is_empty())
            .count()
            >= 2
    }
}

/// The value of an `OpenMetrics` sample `name` (no labels).
fn metric(exposition: &str, name: &str) -> f64 {
    exposition
        .lines()
        .find_map(|l| l.strip_prefix(name).and_then(|r| r.strip_prefix(' ')))
        .unwrap_or_else(|| panic!("{name} not exported:\n{exposition}"))
        .trim()
        .parse()
        .unwrap()
}

