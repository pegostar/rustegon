/// `rustegon init` with the admin password file, returning that file's path.
fn init(env: &Env) -> String {
    let pw = env.write("admin.pw", &format!("{ADMIN_PASSWORD}\n"));
    env.init(&["--admin-password-file", &pw]).ok();
    pw
}

/// An online command (`backup …`, `snapshot …`, `dump`, `restore`): connection options after
/// the subcommand.
fn online_as(env: &Env, daemon: &Daemon, args: &[&str], user: &str, password: &str) -> Run {
    let ca = env.ca();
    let mut v: Vec<&str> = args.to_vec();
    v.extend(conn(env, daemon, &ca));
    v.extend(["--user", user]);
    env.cli(&v, &[("RUSTEGON_PASSWORD", password)])
}

fn online(env: &Env, daemon: &Daemon, args: &[&str]) -> Run {
    online_as(env, daemon, args, "admin", ADMIN_PASSWORD)
}

/// `rustegon user <conn> --user admin <rest…>`.
fn user_admin(env: &Env, daemon: &Daemon, rest: &[&str], extra_env: &[(&str, &str)]) -> Run {
    let ca = env.ca();
    let mut v = vec!["user"];
    v.extend(conn(env, daemon, &ca));
    v.extend(["--user", "admin"]);
    v.extend_from_slice(rest);
    let mut vars = vec![("RUSTEGON_PASSWORD", ADMIN_PASSWORD)];
    vars.extend_from_slice(extra_env);
    env.cli(&v, &vars)
}

fn shell(env: &Env, daemon: &Daemon, script: &str) -> Run {
    let ca = env.ca();
    let mut v = vec!["shell"];
    v.extend(conn(env, daemon, &ca));
    v.extend(["--user", "admin", "-c", script]);
    env.cli(&v, &[("RUSTEGON_PASSWORD", ADMIN_PASSWORD)])
}

/// Result rows of a query (JSON lines on stdout).
fn rows(env: &Env, daemon: &Daemon, query: &str) -> Vec<String> {
    shell(env, daemon, query)
        .ok()
        .stdout
        .lines()
        .map(str::to_owned)
        .collect()
}

/// Rows parsed as JSON objects without `_rev` (regenerated by a logical restore, PD-067).
fn docs(env: &Env, daemon: &Daemon, query: &str) -> Vec<Json> {
    rows(env, daemon, query)
        .iter()
        .map(|r| {
            let mut v: Json = serde_json::from_str(r).unwrap();
            v.as_object_mut().unwrap().remove("_rev");
            v
        })
        .collect()
}

/// The integer `_id`s of `FROM <coll> SELECT _id ORDER BY _id`.
fn ids(env: &Env, daemon: &Daemon, coll: &str) -> Vec<usize> {
    rows(env, daemon, &format!("FROM {coll} SELECT _id ORDER BY _id"))
        .iter()
        .map(|r| {
            let v: Json = serde_json::from_str(r).unwrap();
            usize::try_from(v["_id"].as_u64().unwrap()).unwrap()
        })
        .collect()
}

/// The sum of `bal` over `shop.acct`.
fn balance_sum(env: &Env, daemon: &Daemon) -> i64 {
    rows(env, daemon, "FROM shop.acct SELECT bal")
        .iter()
        .map(|r| {
            serde_json::from_str::<Json>(r).unwrap()["bal"]
                .as_i64()
                .unwrap()
        })
        .sum()
}

/// The backup id of `created <id>\t…` (CLI `backup create`).
fn created_id(run: &Run) -> String {
    run.stdout
        .strip_prefix("created ")
        .and_then(|l| l.split('\t').next())
        .unwrap_or_else(|| panic!("{}", run.stdout))
        .to_owned()
}

/// The `key=value` field of a tab-separated CLI line.
fn field<'a>(line: &'a str, key: &str) -> &'a str {
    line.split('\t')
        .find_map(|f| f.strip_prefix(key).and_then(|r| r.strip_prefix('=')))
        .unwrap_or_else(|| panic!("no {key} in {line}"))
}

/// Puts the store of an offline restore (`<into>/store`) in place of the node's store, the
/// node's own store moved aside to `<root>/<aside>` (the node keeps its certificates and
/// configuration, backup-restore.md "Offline restore").
fn swap_store(env: &Env, into: &Path, aside: &str) {
    std::fs::rename(env.data_dir().join("store"), env.path(aside)).unwrap();
    std::fs::rename(into.join("store"), env.data_dir().join("store")).unwrap();
}

/// Background writers through the CLI: one inserts `shop.log` documents with consecutive
/// `_id`s in batches (each statement commits on its own, in order), one moves balance between
/// `shop.acct` documents in interactive transactions (sum invariant). A transfer may fail on a
/// conflict or abort (the whole transaction is then discarded); an insert batch must succeed.
struct Writers {
    stop: AtomicBool,
    /// `_id`s below this were acknowledged (whole batches).
    acked: AtomicUsize,
    /// `_id`s below this were sent (batches started).
    started: AtomicUsize,
    transfers: AtomicUsize,
}

impl Writers {
    fn new() -> Self {
        Self {
            stop: AtomicBool::new(false),
            acked: AtomicUsize::new(0),
            started: AtomicUsize::new(0),
            transfers: AtomicUsize::new(0),
        }
    }

    fn spawn<'s>(&'s self, s: &'s thread::Scope<'s, '_>, env: &'s Env, daemon: &'s Daemon) {
        s.spawn(move || {
            let mut next = 0;
            while !self.stop.load(Ordering::SeqCst) {
                let script = (next..next + BATCH)
                    .map(|i| format!("INSERT INTO shop.log VALUE {{_id: {i}, w: 'w{i}'}}"))
                    .collect::<Vec<_>>()
                    .join("; ");
                self.started.store(next + BATCH, Ordering::SeqCst);
                shell(env, daemon, &script).ok();
                next += BATCH;
                self.acked.store(next, Ordering::SeqCst);
            }
        });
        s.spawn(move || {
            let mut i = 0i64;
            while !self.stop.load(Ordering::SeqCst) {
                let (from, to) = (i % 5, (i + 2) % 5);
                let script = format!(
                    "BEGIN; UPDATE shop.acct SET bal = bal - 1 WHERE _id = {from}; \
                     UPDATE shop.acct SET bal = bal + 1 WHERE _id = {to}; COMMIT"
                );
                if shell(env, daemon, &script).code == Some(0) {
                    self.transfers.fetch_add(1, Ordering::SeqCst);
                }
                i += 1;
            }
        });
    }

    /// Waits until both writers made progress.
    fn wait_for_progress(&self, inserts: usize) {
        let deadline = Instant::now() + Duration::from_secs(120);
        while self.acked.load(Ordering::SeqCst) < inserts
            || self.transfers.load(Ordering::SeqCst) == 0
        {
            assert!(Instant::now() < deadline, "the writers made no progress");
            thread::sleep(Duration::from_millis(50));
        }
    }
}

