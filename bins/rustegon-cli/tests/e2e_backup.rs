/// TC-BKP-013 / AC-BKP-006 (FR-BKP-007, PD-067, PD-084): `rustegon dump` while a CLI writer
/// keeps inserting; `rustegon restore` into another, empty server recreates the database with
/// documents (system fields kept, `_rev` regenerated), the validator and the index definitions
/// equal to the source; the dumped writer ids are a prefix covering every insert acknowledged
/// before the dump started; a second restore without `--drop` is refused (RGN-1031), with
/// `--drop` it replaces what changed on the target since.
#[test]
fn tc_bkp_013_e2e_dump_under_writes_restores_into_another_server() {
    let src = Env::new();
    let pw = init(&src);
    let daemon = src.start(&["--admin-password-file", &pw]);
    shell(&src, &daemon, SCHEMA).ok();
    shell(
        &src,
        &daemon,
        "CREATE INDEX ix_bal ON shop.acct (bal); INSERT INTO shop.acct VALUE {_id: 5, bal: 7, \
         tags: ['a', 'b'], nested: {k: 1.5}}",
    )
    .ok();
    let ca = src.ca();
    let token = rest_login(&ca, &daemon, "admin", ADMIN_PASSWORD);
    let validator_path = "/api/v1/databases/shop/collections/acct/validator";
    let schema = json!({"$jsonSchema": {"properties": {"bal": {"minimum": 0}}}});
    https(
        &ca,
        daemon.http_port,
        "PUT",
        validator_path,
        Some(&token),
        Some(&json!({"definition": schema, "level": "strict"})),
    )
    .ok();
    let schema_of = |ca: &str, daemon: &Daemon, token: &str| {
        let validator = https(
            ca,
            daemon.http_port,
            "GET",
            validator_path,
            Some(token),
            None,
        )
        .ok()
        .json()["validator"]
            .clone();
        let indexes: Vec<Json> = https(
            ca,
            daemon.http_port,
            "GET",
            "/api/v1/databases/shop/collections/acct/indexes",
            Some(token),
            None,
        )
        .ok()
        .json()["indexes"]
            .as_array()
            .unwrap()
            .iter()
            .map(|i| i["definition"].clone())
            .collect();
        (validator, indexes)
    };
    let source_schema = schema_of(&ca, &daemon, &token);
    assert_eq!(source_schema.0["level"], "strict", "{source_schema:?}");
    assert!(!source_schema.1.is_empty(), "{source_schema:?}");

    let dump_dir = src.path("dump");
    let dump_s = dump_dir.display().to_string();
    let writers = Writers::new();
    let (acked_before, dumped) = thread::scope(|s| {
        writers.spawn(s, &src, &daemon);
        writers.wait_for_progress(2 * BATCH);
        let acked_before = writers.acked.load(Ordering::SeqCst);
        let dumped = online(&src, &daemon, &["dump", "--out", &dump_s]).ok();
        writers.stop.store(true, Ordering::SeqCst);
        (acked_before, dumped)
    });
    assert!(dumped.stdout.contains(" at T="), "{}", dumped.stdout);
    // The transfer writer kept moving balance during the dump: the dump's own `shop.acct` is
    // the state at T, and a torn transfer would break the sum.
    let dumped_acct = ndjson_docs(&dump_dir.join("shop").join("acct.ndjson"));
    assert_eq!(dumped_acct.len(), 6);
    let sum: i64 = dumped_acct.iter().map(|d| d["bal"].as_i64().unwrap()).sum();
    assert_eq!(sum, 500 + 7, "a transfer was torn in the dump");
    let dumped_log: Vec<usize> = std::fs::read_to_string(dump_dir.join("shop").join("log.ndjson"))
        .unwrap()
        .lines()
        .map(|l| {
            usize::try_from(
                serde_json::from_str::<Json>(l).unwrap()["_id"]
                    .as_u64()
                    .unwrap(),
            )
            .unwrap()
        })
        .collect();
    let n = dumped_log.len();
    let mut sorted = dumped_log.clone();
    sorted.sort_unstable();
    assert_eq!(sorted, (0..n).collect::<Vec<_>>(), "not a prefix");
    assert!(n >= acked_before, "{n} < {acked_before}");

    // Another server, empty.
    let dst = Env::new();
    let pw2 = init(&dst);
    let target = dst.start(&["--admin-password-file", &pw2]);
    let restored = online(&dst, &target, &["restore", "--from", &dump_s]).ok();
    assert!(
        restored
            .stdout
            .contains("restored shop.acct\tdocuments=6\tindexes=1"),
        "{}",
        restored.stdout
    );
    assert_eq!(
        docs(&dst, &target, "FROM shop.acct ORDER BY _id"),
        dumped_acct
    );
    assert_eq!(ids(&dst, &target, "shop.log"), (0..n).collect::<Vec<_>>());
    let dst_ca = dst.ca();
    let dst_token = rest_login(&dst_ca, &target, "admin", ADMIN_PASSWORD);
    assert_eq!(schema_of(&dst_ca, &target, &dst_token), source_schema);
    let invalid = shell(
        &dst,
        &target,
        "INSERT INTO shop.acct VALUE {_id: 9, bal: -1}",
    )
    .failed();
    assert!(
        invalid.stderr.contains("1006"),
        "validator restored: {}",
        invalid.stderr
    );

    // A second dump of the now quiet source: its state at T is the live state, so the target
    // must equal the source document for document after `restore --drop`.
    let dump2 = src.path("dump2").display().to_string();
    online(&src, &daemon, &["dump", "--out", &dump2]).ok();
    let source_acct = docs(&src, &daemon, "FROM shop.acct ORDER BY _id");
    let source_log = ids(&src, &daemon, "shop.log");
    src.assert_never_printed(ADMIN_PASSWORD);
    let src_output = daemon.stop();
    assert_not_in_node_output(&src, &src_output, &[ADMIN_PASSWORD, &token]);
    shell(
        &dst,
        &target,
        "INSERT INTO shop.acct VALUE {_id: 10, bal: 1}; DELETE FROM shop.acct WHERE _id = 0",
    )
    .ok();
    let again = online(&dst, &target, &["restore", "--from", &dump2]).failed();
    assert!(again.stderr.contains("1031"), "{}", again.stderr);
    online(&dst, &target, &["restore", "--from", &dump2, "--drop"]).ok();
    assert_eq!(
        docs(&dst, &target, "FROM shop.acct ORDER BY _id"),
        source_acct
    );
    assert_eq!(ids(&dst, &target, "shop.log"), source_log);
    assert_eq!(schema_of(&dst_ca, &target, &dst_token), source_schema);
    target.stop();
}

/// The documents of a dump's `.ndjson` file without `_rev`, in `_id` order.
fn ndjson_docs(path: &Path) -> Vec<Json> {
    let mut docs: Vec<Json> = std::fs::read_to_string(path)
        .unwrap()
        .lines()
        .map(|l| {
            let mut v: Json = serde_json::from_str(l).unwrap();
            v.as_object_mut().unwrap().remove("_rev");
            v
        })
        .collect();
    docs.sort_by_key(|d| d["_id"].as_u64());
    docs
}

